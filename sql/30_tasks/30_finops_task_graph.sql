USE DATABASE FINOPS_DEV;
USE SCHEMA FINOPS;

-- Keep the root suspended while changing this traditional task graph.
-- No WAREHOUSE clause means every task uses Snowflake-managed serverless compute.

CREATE OR REPLACE TASK FINOPS_ROOT_TASK
  SCHEDULE = 'USING CRON 0 12 * * * UTC'
  OVERLAP_POLICY = NO_OVERLAP
AS
EXECUTE IMMEDIATE $$
DECLARE
  V_RUN_ID STRING;
  V_SCHEDULED_AT TIMESTAMP_LTZ;
  V_ANALYSIS_DATE DATE;
BEGIN
  V_RUN_ID := SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID');
  V_SCHEDULED_AT := SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_ORIGINAL_SCHEDULED_TIMESTAMP')::TIMESTAMP_LTZ;
  V_ANALYSIS_DATE := DATEADD(DAY, -1, TO_DATE(CONVERT_TIMEZONE('UTC', V_SCHEDULED_AT)));
  CALL SP_FINOPS_BEGIN_RUN(:V_RUN_ID, :V_ANALYSIS_DATE, :V_SCHEDULED_AT);
END;
$$;

CREATE OR REPLACE TASK FINOPS_CHECK_COST
