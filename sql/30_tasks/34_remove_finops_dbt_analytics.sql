-- Roll back the optional dbt node while leaving the base graph suspended.

USE ROLE FINOPS_TASK_OWNER;
USE DATABASE FINOPS_DEV;
USE SCHEMA FINOPS;

ALTER TASK FINOPS_ROOT_TASK SUSPEND;
ALTER TASK FINOPS_CHECK_COST SUSPEND;
ALTER TASK FINOPS_CHECK_ERRORS SUSPEND;
ALTER TASK FINOPS_CHECK_WAREHOUSE SUSPEND;
ALTER TASK FINOPS_CHECK_QUERIES SUSPEND;
ALTER TASK FINOPS_CHECK_AI SUSPEND;
ALTER TASK FINOPS_CHECK_OTHER_COSTS SUSPEND;
ALTER TASK FINOPS_DBT_ANALYTICS SUSPEND;
ALTER TASK FINOPS_REPORT_TASK SUSPEND;
ALTER TASK FINOPS_ALERT_TASK SUSPEND;
ALTER TASK FINOPS_FINALIZER SUSPEND;

UPDATE FINOPS_CONFIG
SET
  CONFIG_VALUE = TO_VARIANT(FALSE),
  UPDATED_AT = CURRENT_TIMESTAMP(),
  UPDATED_BY = CURRENT_USER()
WHERE MODULE_NAME = 'DBT_ANALYTICS'
  AND CONFIG_KEY = 'ENABLED';

CREATE OR REPLACE TASK FINOPS_REPORT_TASK
  AFTER
    FINOPS_CHECK_COST,
    FINOPS_CHECK_ERRORS,
    FINOPS_CHECK_WAREHOUSE,
    FINOPS_CHECK_QUERIES,
    FINOPS_CHECK_AI,
    FINOPS_CHECK_OTHER_COSTS
AS
EXECUTE IMMEDIATE $$
DECLARE
  V_RUN_ID STRING;
BEGIN
  V_RUN_ID := SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID');
  CALL SP_FINOPS_BUILD_REPORT(:V_RUN_ID);
END;
$$;

DROP TASK IF EXISTS FINOPS_DBT_ANALYTICS;
