-- Optional overlay: add one warehouse-backed native dbt node to the suspended graph.
-- Apply 05_finops_dbt_task_integration_grants.sql and
-- 30_finops_dbt_analytics.sql first. This script never resumes the graph.

USE ROLE FINOPS_TASK_OWNER;
USE DATABASE FINOPS_DEV;
USE SCHEMA FINOPS;

ALTER TASK FINOPS_ROOT_TASK SUSPEND;
ALTER TASK FINOPS_CHECK_COST SUSPEND;
ALTER TASK FINOPS_CHECK_ERRORS SUSPEND;
ALTER TASK FINOPS_CHECK_WAREHOUSE SUSPEND;
ALTER TASK FINOPS_CHECK_QUERIES SUSPEND;
ALTER TASK FINOPS_CHECK_AI SUSPEND;
ALTER TASK FINOPS_CHECK_OTHER_COSTS SUSPEND;
ALTER TASK FINOPS_REPORT_TASK SUSPEND;
ALTER TASK FINOPS_ALERT_TASK SUSPEND;
ALTER TASK FINOPS_FINALIZER SUSPEND;

CREATE OR REPLACE TASK FINOPS_DBT_ANALYTICS
  WAREHOUSE = FINOPS_DBT_WAREHOUSE
  AFTER FINOPS_ROOT_TASK
AS
EXECUTE IMMEDIATE $$
DECLARE
  V_RUN_ID STRING;
BEGIN
  V_RUN_ID := SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID');
  CALL SP_FINOPS_RUN_DBT_ANALYTICS(:V_RUN_ID);
END;
$$;

CREATE OR REPLACE TASK FINOPS_REPORT_TASK
  AFTER
    FINOPS_CHECK_COST,
    FINOPS_CHECK_ERRORS,
    FINOPS_CHECK_WAREHOUSE,
    FINOPS_CHECK_QUERIES,
    FINOPS_CHECK_AI,
    FINOPS_CHECK_OTHER_COSTS,
    FINOPS_DBT_ANALYTICS
AS
EXECUTE IMMEDIATE $$
DECLARE
  V_RUN_ID STRING;
BEGIN
  V_RUN_ID := SYSTEM$TASK_RUNTIME_INFO('CURRENT_TASK_GRAPH_RUN_GROUP_ID');
  CALL SP_FINOPS_BUILD_REPORT(:V_RUN_ID);
END;
$$;

MERGE INTO FINOPS_CONFIG target
USING (
  SELECT
    'DBT_ANALYTICS' AS MODULE_NAME,
    'ENABLED' AS CONFIG_KEY,
    TO_VARIANT(TRUE) AS CONFIG_VALUE,
    'BOOLEAN' AS VALUE_TYPE,
    TRUE AS ENABLED,
    'Include the validated native dbt node in operational graph runs.' AS DESCRIPTION
) source
ON target.MODULE_NAME = source.MODULE_NAME
  AND target.CONFIG_KEY = source.CONFIG_KEY
WHEN MATCHED THEN UPDATE SET
  CONFIG_VALUE = TO_VARIANT(TRUE),
  ENABLED = TRUE,
  UPDATED_AT = CURRENT_TIMESTAMP(),
  UPDATED_BY = CURRENT_USER()
WHEN NOT MATCHED THEN INSERT (
  MODULE_NAME, CONFIG_KEY, CONFIG_VALUE, VALUE_TYPE, ENABLED, DESCRIPTION
) VALUES (
  source.MODULE_NAME, source.CONFIG_KEY, source.CONFIG_VALUE,
  source.VALUE_TYPE, source.ENABLED, source.DESCRIPTION
);
