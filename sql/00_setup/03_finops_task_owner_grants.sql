-- One-time administrative bootstrap authorized for the clean FINOPS_DEV install.
-- The deployment helper later forces this role as the primary role and disables
-- secondary roles, so every graph task is created under one owner.

USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS FINOPS_DEV;
CREATE SCHEMA IF NOT EXISTS FINOPS_DEV.FINOPS;
CREATE ROLE IF NOT EXISTS FINOPS_TASK_OWNER;

GRANT ROLE FINOPS_TASK_OWNER TO USER "gvilabracho";

GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE FINOPS_TASK_OWNER;
GRANT USAGE ON DATABASE FINOPS_DEV TO ROLE FINOPS_TASK_OWNER;
GRANT USAGE ON SCHEMA FINOPS_DEV.FINOPS TO ROLE FINOPS_TASK_OWNER;
GRANT CREATE TABLE ON SCHEMA FINOPS_DEV.FINOPS TO ROLE FINOPS_TASK_OWNER;
GRANT CREATE VIEW ON SCHEMA FINOPS_DEV.FINOPS TO ROLE FINOPS_TASK_OWNER;
GRANT CREATE FUNCTION ON SCHEMA FINOPS_DEV.FINOPS TO ROLE FINOPS_TASK_OWNER;
GRANT CREATE PROCEDURE ON SCHEMA FINOPS_DEV.FINOPS TO ROLE FINOPS_TASK_OWNER;
GRANT CREATE TASK ON SCHEMA FINOPS_DEV.FINOPS TO ROLE FINOPS_TASK_OWNER;

GRANT EXECUTE TASK ON ACCOUNT TO ROLE FINOPS_TASK_OWNER;
GRANT EXECUTE MANAGED TASK ON ACCOUNT TO ROLE FINOPS_TASK_OWNER;
GRANT DATABASE ROLE SNOWFLAKE.USAGE_VIEWER TO ROLE FINOPS_TASK_OWNER;
GRANT DATABASE ROLE SNOWFLAKE.GOVERNANCE_VIEWER TO ROLE FINOPS_TASK_OWNER;

