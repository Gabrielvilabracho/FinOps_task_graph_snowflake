-- DATALAB.SPAIN is a managed-access schema owned by SYSADMIN.
-- Run schema-level grants as SYSADMIN (or a role with MANAGE GRANTS).
-- Run account-level task grants as ACCOUNTADMIN if they are not already delegated.

USE ROLE SYSADMIN;

GRANT USAGE ON DATABASE DATALAB TO ROLE GG_APP_CC_REC_DATAWARE_DMO;
GRANT USAGE ON SCHEMA DATALAB.SPAIN TO ROLE GG_APP_CC_REC_DATAWARE_DMO;
GRANT SELECT ON ALL TABLES IN SCHEMA DATALAB.SPAIN TO ROLE GG_APP_CC_REC_DATAWARE_DMO;
GRANT SELECT ON FUTURE TABLES IN SCHEMA DATALAB.SPAIN TO ROLE GG_APP_CC_REC_DATAWARE_DMO;
GRANT SELECT ON ALL VIEWS IN SCHEMA DATALAB.SPAIN TO ROLE GG_APP_CC_REC_DATAWARE_DMO;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA DATALAB.SPAIN TO ROLE GG_APP_CC_REC_DATAWARE_DMO;
GRANT USAGE ON ALL FUNCTIONS IN SCHEMA DATALAB.SPAIN TO ROLE GG_APP_CC_REC_DATAWARE_DMO;
GRANT USAGE ON FUTURE FUNCTIONS IN SCHEMA DATALAB.SPAIN TO ROLE GG_APP_CC_REC_DATAWARE_DMO;
GRANT USAGE ON ALL PROCEDURES IN SCHEMA DATALAB.SPAIN TO ROLE GG_APP_CC_REC_DATAWARE_DMO;
GRANT USAGE ON FUTURE PROCEDURES IN SCHEMA DATALAB.SPAIN TO ROLE GG_APP_CC_REC_DATAWARE_DMO;
GRANT MONITOR ON ALL TASKS IN SCHEMA DATALAB.SPAIN TO ROLE GG_APP_CC_REC_DATAWARE_DMO;

-- The graph owner needs these account privileges for serverless tasks.
USE ROLE ACCOUNTADMIN;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE GG_APP_CC_REC_DATAWARE_DMO;
GRANT EXECUTE MANAGED TASK ON ACCOUNT TO ROLE GG_APP_CC_REC_DATAWARE_DMO;
GRANT DATABASE ROLE SNOWFLAKE.USAGE_VIEWER TO ROLE GG_APP_CC_REC_DATAWARE_DMO;

