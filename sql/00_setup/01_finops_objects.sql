CREATE TABLE IF NOT EXISTS FINOPS_CONFIG (
  MODULE_NAME STRING NOT NULL,
  CONFIG_KEY STRING NOT NULL,
  CONFIG_VALUE VARIANT,
  VALUE_TYPE STRING NOT NULL,
  ENABLED BOOLEAN NOT NULL DEFAULT TRUE,
  DESCRIPTION STRING,
  UPDATED_AT TIMESTAMP_LTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  UPDATED_BY STRING NOT NULL DEFAULT CURRENT_USER(),
  PRIMARY KEY (MODULE_NAME, CONFIG_KEY)
);

