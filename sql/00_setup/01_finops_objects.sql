MERGE INTO FINOPS_CONFIG target
USING (
  SELECT * FROM VALUES
    ('COST', 'DAILY_CREDIT_THRESHOLD', TO_VARIANT(25::NUMBER), 'NUMBER', TRUE, 'Alert when previous-day account credits exceed this value.'),
    ('COST', 'GROWTH_RATIO_THRESHOLD', TO_VARIANT(0.30::FLOAT), 'FLOAT', TRUE, 'Alert when day-over-day credit growth exceeds this ratio.'),
    ('ALERT', 'ENABLED', TO_VARIANT(FALSE), 'BOOLEAN', TRUE, 'Master switch for native email delivery.'),
    ('ALERT', 'EMAIL_INTEGRATION', PARSE_JSON('null'), 'STRING', TRUE, 'Approved Snowflake email notification integration name.'),
    ('ALERT', 'RECIPIENTS', PARSE_JSON('null'), 'STRING', TRUE, 'Comma-separated verified Snowflake user email addresses.')
) source (MODULE_NAME, CONFIG_KEY, CONFIG_VALUE, VALUE_TYPE, ENABLED, DESCRIPTION)
ON target.MODULE_NAME = source.MODULE_NAME AND target.CONFIG_KEY = source.CONFIG_KEY
WHEN NOT MATCHED THEN INSERT (
  MODULE_NAME, CONFIG_KEY, CONFIG_VALUE, VALUE_TYPE, ENABLED, DESCRIPTION
) VALUES (
  source.MODULE_NAME, source.CONFIG_KEY, source.CONFIG_VALUE, source.VALUE_TYPE,
  source.ENABLED, source.DESCRIPTION
);

CREATE OR REPLACE VIEW FINOPS_LATEST_RUN AS
SELECT *
FROM FINOPS_RUN
QUALIFY ROW_NUMBER() OVER (ORDER BY STARTED_AT DESC) = 1;

CREATE OR REPLACE VIEW FINOPS_OPEN_ATTENTION AS
SELECT
  run.ANALYSIS_DATE,
  run.RUN_ID,
  run.STATUS AS RUN_STATUS,
  finding.MODULE_NAME,
  finding.FINDING_TYPE,
  finding.SEVERITY,
  finding.METRIC_NAME,
  finding.METRIC_VALUE,
  finding.METRIC_UNIT,
  finding.THRESHOLD_VALUE,
  finding.DETAILS,
  finding.DETECTED_AT
FROM FINOPS_RUN run
JOIN FINOPS_FINDING finding ON finding.RUN_ID = run.RUN_ID
WHERE run.STATUS IN ('ATTENTION_REQUIRED', 'DATA_INCOMPLETE', 'FAILED')
  AND finding.SEVERITY IN ('WARNING', 'CRITICAL');
