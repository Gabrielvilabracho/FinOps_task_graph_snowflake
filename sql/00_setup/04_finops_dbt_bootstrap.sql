-- One-time administrative bootstrap for the native FinOps dbt project.
-- This does not deploy the project and never resumes the operational Task Graph.

USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS FINOPS_DBT_WAREHOUSE
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE ROLE IF NOT EXISTS FINOPS_DBT_ROLE;

GRANT ROLE FINOPS_DBT_ROLE TO USER "gvilabracho";
GRANT USAGE ON WAREHOUSE FINOPS_DBT_WAREHOUSE TO ROLE FINOPS_DBT_ROLE;
GRANT USAGE ON DATABASE FINOPS_DEV TO ROLE FINOPS_DBT_ROLE;
GRANT CREATE SCHEMA ON DATABASE FINOPS_DEV TO ROLE FINOPS_DBT_ROLE;
GRANT USAGE ON SCHEMA FINOPS_DEV.FINOPS TO ROLE FINOPS_DBT_ROLE;
GRANT CREATE DBT PROJECT ON SCHEMA FINOPS_DEV.FINOPS TO ROLE FINOPS_DBT_ROLE;
GRANT DATABASE ROLE SNOWFLAKE.USAGE_VIEWER TO ROLE FINOPS_DBT_ROLE;
