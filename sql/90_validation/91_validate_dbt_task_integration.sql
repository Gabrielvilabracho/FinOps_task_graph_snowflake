USE ROLE FINOPS_TASK_OWNER;
USE DATABASE FINOPS_DEV;
USE SCHEMA FINOPS;

SHOW TASKS IN SCHEMA FINOPS_DEV.FINOPS;

EXECUTE IMMEDIATE $$
DECLARE
  V_EXPECTED_TASK_COUNT NUMBER;
  V_SUSPENDED_TASK_COUNT NUMBER;
  V_UNEXPECTED_TASK_COUNT NUMBER;
  V_DBT_ENABLED BOOLEAN;
  V_DBT_TASK_DDL STRING;
  V_REPORT_TASK_DDL STRING;
  EXPECTED_TASK_COUNT_INVALID EXCEPTION (-20101, 'Expected exactly eleven named FinOps tasks.');
  SUSPENDED_TASK_COUNT_INVALID EXCEPTION (-20102, 'Every integrated FinOps task must be suspended.');
  DBT_CONFIG_INVALID EXCEPTION (-20103, 'DBT_ANALYTICS configuration must be enabled.');
  DBT_TASK_CONTRACT_INVALID EXCEPTION (-20104, 'DBT task warehouse or wrapper contract is invalid.');
  REPORT_FAN_IN_INVALID EXCEPTION (-20105, 'Report task does not depend on the dbt node.');
  UNEXPECTED_TASK_COUNT_INVALID EXCEPTION (-20106, 'Unexpected FINOPS_* tasks exist in the integrated graph.');
BEGIN
  SELECT
    COUNT_IF("name" IN (
      'FINOPS_ROOT_TASK',
      'FINOPS_CHECK_COST',
      'FINOPS_CHECK_ERRORS',
      'FINOPS_CHECK_WAREHOUSE',
      'FINOPS_CHECK_QUERIES',
      'FINOPS_CHECK_AI',
      'FINOPS_CHECK_OTHER_COSTS',
      'FINOPS_DBT_ANALYTICS',
      'FINOPS_REPORT_TASK',
      'FINOPS_ALERT_TASK',
      'FINOPS_FINALIZER'
    )),
    COUNT_IF("name" LIKE 'FINOPS_%' AND UPPER("state") = 'SUSPENDED'),
    COUNT_IF("name" LIKE 'FINOPS_%' AND "name" NOT IN (
      'FINOPS_ROOT_TASK',
      'FINOPS_CHECK_COST',
      'FINOPS_CHECK_ERRORS',
      'FINOPS_CHECK_WAREHOUSE',
      'FINOPS_CHECK_QUERIES',
      'FINOPS_CHECK_AI',
      'FINOPS_CHECK_OTHER_COSTS',
      'FINOPS_DBT_ANALYTICS',
      'FINOPS_REPORT_TASK',
      'FINOPS_ALERT_TASK',
      'FINOPS_FINALIZER'
    ))
  INTO :V_EXPECTED_TASK_COUNT, :V_SUSPENDED_TASK_COUNT, :V_UNEXPECTED_TASK_COUNT
  FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()))
  WHERE "name" LIKE 'FINOPS_%';

  SELECT COALESCE(COUNT_IF(CONFIG_VALUE::BOOLEAN = TRUE), 0) = 1
    INTO :V_DBT_ENABLED
  FROM FINOPS_CONFIG
  WHERE MODULE_NAME = 'DBT_ANALYTICS'
    AND CONFIG_KEY = 'ENABLED'
    AND ENABLED;

  SELECT GET_DDL('TASK', 'FINOPS_DEV.FINOPS.FINOPS_DBT_ANALYTICS')
    INTO :V_DBT_TASK_DDL;
  SELECT GET_DDL('TASK', 'FINOPS_DEV.FINOPS.FINOPS_REPORT_TASK')
    INTO :V_REPORT_TASK_DDL;

  IF (V_EXPECTED_TASK_COUNT <> 11) THEN
    RAISE EXPECTED_TASK_COUNT_INVALID;
  END IF;
  IF (V_SUSPENDED_TASK_COUNT <> 11) THEN
    RAISE SUSPENDED_TASK_COUNT_INVALID;
  END IF;
  IF (V_UNEXPECTED_TASK_COUNT <> 0) THEN
    RAISE UNEXPECTED_TASK_COUNT_INVALID;
  END IF;
  IF (NOT V_DBT_ENABLED) THEN
    RAISE DBT_CONFIG_INVALID;
  END IF;
  IF (
    NOT REGEXP_LIKE(
      UPPER(V_DBT_TASK_DDL),
      '.*WAREHOUSE[[:space:]]*=[[:space:]]*FINOPS_DBT_WAREHOUSE.*',
      'is'
    )
    OR NOT CONTAINS(UPPER(V_DBT_TASK_DDL), 'SP_FINOPS_RUN_DBT_ANALYTICS')
  ) THEN
    RAISE DBT_TASK_CONTRACT_INVALID;
  END IF;
  IF (NOT CONTAINS(UPPER(V_REPORT_TASK_DDL), 'FINOPS_DBT_ANALYTICS')) THEN
    RAISE REPORT_FAN_IN_INVALID;
  END IF;

  RETURN OBJECT_CONSTRUCT(
    'EXPECTED_TASK_COUNT', V_EXPECTED_TASK_COUNT,
    'SUSPENDED_TASK_COUNT', V_SUSPENDED_TASK_COUNT,
    'UNEXPECTED_TASK_COUNT', V_UNEXPECTED_TASK_COUNT,
    'DBT_ANALYTICS_ENABLED', V_DBT_ENABLED
  );
END;
$$;
