USE DATABASE DATALAB;
USE SCHEMA SPAIN;

-- Required persisted objects.
SHOW TABLES LIKE 'FINOPS_%' IN SCHEMA DATALAB.SPAIN;
SHOW VIEWS LIKE 'FINOPS_%' IN SCHEMA DATALAB.SPAIN;
SHOW USER FUNCTIONS LIKE 'FINOPS_%' IN SCHEMA DATALAB.SPAIN;
SHOW PROCEDURES LIKE 'SP_FINOPS_%' IN SCHEMA DATALAB.SPAIN;
SHOW TASKS IN SCHEMA DATALAB.SPAIN;

-- The graph must have one root, six analysis children, report, alert, and finalizer.
SELECT
  "name" AS TASK_NAME,
  "state" AS TASK_STATE,
  "schedule" AS TASK_SCHEDULE,
  "predecessors" AS PREDECESSORS,
  "condition" AS TASK_CONDITION,
  "owner" AS TASK_OWNER
FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()))
WHERE "name" IN (
  'FINOPS_ROOT_TASK',
  'FINOPS_CHECK_COST',
  'FINOPS_CHECK_ERRORS',
  'FINOPS_CHECK_WAREHOUSE',
  'FINOPS_CHECK_QUERIES',
  'FINOPS_CHECK_AI',
  'FINOPS_CHECK_OTHER_COSTS',
  'FINOPS_REPORT_TASK',
  'FINOPS_ALERT_TASK',
  'FINOPS_FINALIZER'
)
ORDER BY TASK_NAME;

-- Cost policy boundary checks.
SELECT
  FINOPS_CLASSIFY_COST(20, 18):status::STRING AS EXPECTED_NORMAL,
  FINOPS_CLASSIFY_COST(25.01, 25):status::STRING AS EXPECTED_CREDIT_ATTENTION,
  FINOPS_CLASSIFY_COST(13.01, 10):status::STRING AS EXPECTED_GROWTH_ATTENTION,
  FINOPS_CLASSIFY_COST(13, 10):status::STRING AS EXPECTED_EXACT_BOUNDARY_NORMAL,
  FINOPS_CLASSIFY_COST(10, NULL):status::STRING AS EXPECTED_NO_BASELINE_NORMAL;

-- Configuration remains explicit; alerting must be reviewed before resume.
SELECT MODULE_NAME, CONFIG_KEY, CONFIG_VALUE, VALUE_TYPE, ENABLED
FROM FINOPS_CONFIG
ORDER BY MODULE_NAME, CONFIG_KEY;

-- Recent operational evidence after a smoke run.
SELECT * FROM FINOPS_RUN ORDER BY STARTED_AT DESC LIMIT 10;
SELECT * FROM FINOPS_MODULE_RUN ORDER BY UPDATED_AT DESC LIMIT 60;
SELECT * FROM FINOPS_DAILY_REPORT ORDER BY GENERATED_AT DESC LIMIT 10;
SELECT * FROM FINOPS_ALERT_DELIVERY ORDER BY ATTEMPTED_AT DESC LIMIT 10;
