USE DATABASE FINOPS_DEV;
USE SCHEMA FINOPS;

CREATE OR REPLACE PROCEDURE SP_FINOPS_FINALIZE_RUN(P_RUN_ID STRING)
RETURNS OBJECT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  V_REPORT_RESULT VARIANT;
  V_ALERT_RESULT VARIANT;
  V_OVERALL_STATUS STRING;
BEGIN
  INSERT INTO FINOPS_FINDING (
    RUN_ID, MODULE_NAME, FINDING_TYPE, SEVERITY,
    METRIC_NAME, DETAILS
  )
  SELECT
    module.RUN_ID,
    module.MODULE_NAME,
    'TECHNICAL_FAILURE',
    'CRITICAL',
    'module_completion',
    OBJECT_CONSTRUCT(
      'previous_status', module.STATUS,
      'reason', 'Module did not reach a terminal state before finalization.'
    )
  FROM FINOPS_MODULE_RUN module
  WHERE module.RUN_ID = :P_RUN_ID
    AND module.STATUS IN ('PENDING', 'RUNNING')
    AND NOT EXISTS (
      SELECT 1
      FROM FINOPS_FINDING finding
      WHERE finding.RUN_ID = module.RUN_ID
        AND finding.MODULE_NAME = module.MODULE_NAME
        AND finding.FINDING_TYPE = 'TECHNICAL_FAILURE'
    );

  UPDATE FINOPS_MODULE_RUN
  SET
    STATUS = 'FAILED',
    COMPLETED_AT = CURRENT_TIMESTAMP(),
    ERROR_CODE = COALESCE(ERROR_CODE, 'MODULE_DID_NOT_COMPLETE'),
    ERROR_MESSAGE = COALESCE(
      ERROR_MESSAGE,
      'Module did not reach a terminal state before finalization.'
    ),
    UPDATED_AT = CURRENT_TIMESTAMP()
  WHERE RUN_ID = :P_RUN_ID
    AND STATUS IN ('PENDING', 'RUNNING');

  CALL SP_FINOPS_BUILD_REPORT(:P_RUN_ID) INTO :V_REPORT_RESULT;
  CALL SP_FINOPS_SEND_ALERT(:P_RUN_ID) INTO :V_ALERT_RESULT;

  SELECT STATUS INTO :V_OVERALL_STATUS
  FROM FINOPS_RUN
  WHERE RUN_ID = :P_RUN_ID;

  UPDATE FINOPS_RUN
  SET
    FINALIZER_COMPLETED = TRUE,
    COMPLETED_AT = COALESCE(COMPLETED_AT, CURRENT_TIMESTAMP()),
    UPDATED_AT = CURRENT_TIMESTAMP()
  WHERE RUN_ID = :P_RUN_ID;

  RETURN OBJECT_CONSTRUCT(
    'run_id', P_RUN_ID,
    'status', V_OVERALL_STATUS,
    'report', V_REPORT_RESULT,
    'alert', V_ALERT_RESULT,
    'normal_status', 'NORMAL',
    'business_anomaly_status', 'ATTENTION',
    'rule_gap_status', 'RULE_NOT_CONFIGURED',
    'incomplete_data_status', 'DATA_INCOMPLETE',
    'technical_failure_status', 'FAILED',
    'overall_attention_status', 'ATTENTION_REQUIRED'
  );
EXCEPTION
  WHEN OTHER THEN
    UPDATE FINOPS_RUN
    SET
      STATUS = 'FAILED',
      COMPLETED_AT = CURRENT_TIMESTAMP(),
      FINALIZER_COMPLETED = FALSE,
      UPDATED_AT = CURRENT_TIMESTAMP()
    WHERE RUN_ID = :P_RUN_ID;
    RAISE;
END;
$$;
