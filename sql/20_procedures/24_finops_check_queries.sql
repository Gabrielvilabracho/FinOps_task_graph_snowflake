USE DATABASE DATALAB;
USE SCHEMA SPAIN;

CREATE OR REPLACE PROCEDURE SP_FINOPS_CHECK_QUERIES(
  P_RUN_ID STRING,
  P_ANALYSIS_DATE DATE
)
RETURNS OBJECT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  V_QUERY_COUNT NUMBER;
  V_USERS NUMBER;
  V_WAREHOUSES NUMBER;
  V_ATTRIBUTED_CREDITS NUMBER(38, 9);
  V_MAX_QUERY_CREDITS NUMBER(38, 9);
  V_METRICS VARIANT;
BEGIN
  CALL SP_FINOPS_MARK_MODULE_START(:P_RUN_ID, 'QUERIES');

  SELECT
    COUNT(*),
    COUNT(DISTINCT USER_NAME),
    COUNT(DISTINCT WAREHOUSE_NAME)
  INTO :V_QUERY_COUNT, :V_USERS, :V_WAREHOUSES
  FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
  WHERE TO_DATE(CONVERT_TIMEZONE('UTC', START_TIME)) = :P_ANALYSIS_DATE;

  SELECT
    COALESCE(SUM(CREDITS_ATTRIBUTED_COMPUTE), 0),
    COALESCE(MAX(CREDITS_ATTRIBUTED_COMPUTE), 0)
  INTO :V_ATTRIBUTED_CREDITS, :V_MAX_QUERY_CREDITS
  FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_ATTRIBUTION_HISTORY
  WHERE TO_DATE(CONVERT_TIMEZONE('UTC', START_TIME)) = :P_ANALYSIS_DATE;

  V_METRICS := OBJECT_CONSTRUCT(
    'analysis_date', P_ANALYSIS_DATE,
    'query_count', V_QUERY_COUNT,
    'active_users', V_USERS,
    'active_warehouses', V_WAREHOUSES,
    'attributed_compute_credits', V_ATTRIBUTED_CREDITS,
    'maximum_single_query_credits', V_MAX_QUERY_CREDITS,
    'attribution_latency_note', 'QUERY_ATTRIBUTION_HISTORY can lag up to eight hours.'
  );

  CALL SP_FINOPS_RECORD_RULE_GAP(
    :P_RUN_ID,
    'QUERIES',
    :V_METRICS,
    'Approve the expensive-query rule, exclusions, ownership fields, and severity.'
  );
  RETURN V_METRICS;
EXCEPTION
  WHEN OTHER THEN
    CALL SP_FINOPS_FAIL_MODULE(:P_RUN_ID, 'QUERIES', SQLCODE::STRING, SQLERRM);
    RAISE;
END;
$$;
