USE DATABASE FINOPS_DEV;
USE SCHEMA FINOPS;

CREATE OR REPLACE PROCEDURE SP_FINOPS_CHECK_ERRORS(
  P_RUN_ID STRING,
  P_ANALYSIS_DATE DATE
)
RETURNS OBJECT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  V_ERROR_COUNT NUMBER;
  V_AFFECTED_USERS NUMBER;
  V_AFFECTED_WAREHOUSES NUMBER;
  V_METRICS VARIANT;
BEGIN
  CALL SP_FINOPS_MARK_MODULE_START(:P_RUN_ID, 'ERRORS');

  SELECT
    COUNT(*),
    COUNT(DISTINCT USER_NAME),
    COUNT(DISTINCT WAREHOUSE_NAME)
  INTO :V_ERROR_COUNT, :V_AFFECTED_USERS, :V_AFFECTED_WAREHOUSES
  FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
  WHERE TO_DATE(CONVERT_TIMEZONE('UTC', START_TIME)) = :P_ANALYSIS_DATE
    AND EXECUTION_STATUS IN ('FAIL', 'INCIDENT');

  V_METRICS := OBJECT_CONSTRUCT(
    'analysis_date', P_ANALYSIS_DATE,
    'query_error_count', V_ERROR_COUNT,
    'affected_users', V_AFFECTED_USERS,
    'affected_warehouses', V_AFFECTED_WAREHOUSES
  );

  CALL SP_FINOPS_RECORD_RULE_GAP(
    :P_RUN_ID,
    'ERRORS',
    :V_METRICS,
    'Approve the query-error volume, severity, and exclusion rule.'
  );
  RETURN V_METRICS;
EXCEPTION
  WHEN OTHER THEN
    CALL SP_FINOPS_FAIL_MODULE(:P_RUN_ID, 'ERRORS', SQLCODE::STRING, SQLERRM);
    RAISE;
END;
$$;
