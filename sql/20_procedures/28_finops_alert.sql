USE DATABASE DATALAB;
USE SCHEMA SPAIN;

CREATE OR REPLACE PROCEDURE SP_FINOPS_SEND_ALERT(P_RUN_ID STRING)
RETURNS OBJECT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  V_OVERALL_STATUS STRING;
  V_REPORT_TEXT STRING;
  V_ENABLED BOOLEAN;
  V_INTEGRATION STRING;
  V_RECIPIENTS STRING;
  V_SUBJECT STRING;
  V_ALREADY_DELIVERED NUMBER;
BEGIN
  SELECT OVERALL_STATUS, REPORT_TEXT
  INTO :V_OVERALL_STATUS, :V_REPORT_TEXT
  FROM FINOPS_DAILY_REPORT
  WHERE RUN_ID = :P_RUN_ID
  QUALIFY ROW_NUMBER() OVER (ORDER BY GENERATED_AT DESC) = 1;

  SELECT COUNT(*) INTO :V_ALREADY_DELIVERED
  FROM FINOPS_ALERT_DELIVERY
  WHERE RUN_ID = :P_RUN_ID
    AND CHANNEL = 'EMAIL'
    AND DELIVERY_STATUS = 'DELIVERED';

  IF (V_ALREADY_DELIVERED > 0) THEN
    RETURN OBJECT_CONSTRUCT(
      'run_id', P_RUN_ID,
      'status', 'ALREADY_DELIVERED',
      'overall_status', V_OVERALL_STATUS
    );
  END IF;

  IF (V_OVERALL_STATUS NOT IN ('ATTENTION_REQUIRED', 'DATA_INCOMPLETE', 'FAILED')) THEN
    MERGE INTO FINOPS_ALERT_DELIVERY target
    USING (SELECT :P_RUN_ID AS RUN_ID, 'EMAIL' AS CHANNEL) source
    ON target.RUN_ID = source.RUN_ID AND target.CHANNEL = source.CHANNEL
    WHEN MATCHED THEN UPDATE SET
      target.DELIVERY_STATUS = 'NOT_REQUIRED',
      target.ERROR_MESSAGE = NULL,
      target.ATTEMPTED_AT = CURRENT_TIMESTAMP()
    WHEN NOT MATCHED THEN INSERT (RUN_ID, CHANNEL, DELIVERY_STATUS)
      VALUES (source.RUN_ID, source.CHANNEL, 'NOT_REQUIRED');

    RETURN OBJECT_CONSTRUCT(
      'run_id', P_RUN_ID,
      'status', 'NOT_REQUIRED',
      'overall_status', V_OVERALL_STATUS
    );
  END IF;

  SELECT CONFIG_VALUE::BOOLEAN INTO :V_ENABLED
  FROM FINOPS_CONFIG
  WHERE MODULE_NAME = 'ALERT' AND CONFIG_KEY = 'ENABLED' AND ENABLED;

  SELECT CONFIG_VALUE::STRING INTO :V_INTEGRATION
  FROM FINOPS_CONFIG
  WHERE MODULE_NAME = 'ALERT' AND CONFIG_KEY = 'EMAIL_INTEGRATION' AND ENABLED;

  SELECT CONFIG_VALUE::STRING INTO :V_RECIPIENTS
  FROM FINOPS_CONFIG
  WHERE MODULE_NAME = 'ALERT' AND CONFIG_KEY = 'RECIPIENTS' AND ENABLED;

  IF (NOT V_ENABLED OR V_INTEGRATION IS NULL OR V_RECIPIENTS IS NULL) THEN
    MERGE INTO FINOPS_ALERT_DELIVERY target
    USING (SELECT :P_RUN_ID AS RUN_ID, 'EMAIL' AS CHANNEL) source
    ON target.RUN_ID = source.RUN_ID AND target.CHANNEL = source.CHANNEL
    WHEN MATCHED THEN UPDATE SET
      target.DELIVERY_STATUS = 'NOT_CONFIGURED',
      target.DESTINATION = :V_RECIPIENTS,
      target.ERROR_MESSAGE = 'Alert delivery is disabled or missing approved integration/recipients.',
      target.ATTEMPTED_AT = CURRENT_TIMESTAMP()
    WHEN NOT MATCHED THEN INSERT (
      RUN_ID, CHANNEL, DELIVERY_STATUS, DESTINATION, ERROR_MESSAGE
    ) VALUES (
      source.RUN_ID, source.CHANNEL, 'NOT_CONFIGURED', :V_RECIPIENTS,
      'Alert delivery is disabled or missing approved integration/recipients.'
    );

    RETURN OBJECT_CONSTRUCT(
      'run_id', P_RUN_ID,
      'status', 'NOT_CONFIGURED',
      'overall_status', V_OVERALL_STATUS
    );
  END IF;

  V_SUBJECT := 'Snowflake FinOps: ' || REPLACE(V_OVERALL_STATUS, '_', ' ');
  CALL SYSTEM$SEND_EMAIL(
    :V_INTEGRATION,
    :V_RECIPIENTS,
    :V_SUBJECT,
    :V_REPORT_TEXT,
    'text/plain'
  );

  MERGE INTO FINOPS_ALERT_DELIVERY target
  USING (SELECT :P_RUN_ID AS RUN_ID, 'EMAIL' AS CHANNEL) source
  ON target.RUN_ID = source.RUN_ID AND target.CHANNEL = source.CHANNEL
  WHEN MATCHED THEN UPDATE SET
    target.DELIVERY_STATUS = 'DELIVERED',
    target.DESTINATION = :V_RECIPIENTS,
    target.ERROR_MESSAGE = NULL,
    target.ATTEMPTED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT (
    RUN_ID, CHANNEL, DELIVERY_STATUS, DESTINATION
  ) VALUES (
    source.RUN_ID, source.CHANNEL, 'DELIVERED', :V_RECIPIENTS
  );

  RETURN OBJECT_CONSTRUCT(
    'run_id', P_RUN_ID,
    'status', 'DELIVERED',
    'overall_status', V_OVERALL_STATUS
  );
EXCEPTION
  WHEN OTHER THEN
    MERGE INTO FINOPS_ALERT_DELIVERY target
    USING (SELECT :P_RUN_ID AS RUN_ID, 'EMAIL' AS CHANNEL) source
    ON target.RUN_ID = source.RUN_ID AND target.CHANNEL = source.CHANNEL
    WHEN MATCHED THEN UPDATE SET
      target.DELIVERY_STATUS = 'FAILED',
      target.DESTINATION = :V_RECIPIENTS,
      target.ERROR_MESSAGE = LEFT(SQLERRM, 4000),
      target.ATTEMPTED_AT = CURRENT_TIMESTAMP()
    WHEN NOT MATCHED THEN INSERT (
      RUN_ID, CHANNEL, DELIVERY_STATUS, DESTINATION, ERROR_MESSAGE
    ) VALUES (
      source.RUN_ID, source.CHANNEL, 'FAILED', :V_RECIPIENTS, LEFT(SQLERRM, 4000)
    );

    RETURN OBJECT_CONSTRUCT(
      'run_id', P_RUN_ID,
      'status', 'FAILED',
      'error_message', LEFT(SQLERRM, 4000)
    );
END;
$$;
