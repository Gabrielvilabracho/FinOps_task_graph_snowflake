USE DATABASE DATALAB;
USE SCHEMA SPAIN;

CREATE OR REPLACE PROCEDURE SP_FINOPS_CHECK_COST(
  P_RUN_ID STRING,
  P_ANALYSIS_DATE DATE
)
RETURNS OBJECT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  V_CURRENT_CREDITS NUMBER(38, 9);
  V_PREVIOUS_CREDITS NUMBER(38, 9);
  V_DAILY_THRESHOLD NUMBER(38, 9);
  V_GROWTH_THRESHOLD FLOAT;
  V_POLICY OBJECT;
  V_STATUS STRING;
  V_GROWTH_RATIO FLOAT;
BEGIN
  CALL SP_FINOPS_MARK_MODULE_START(:P_RUN_ID, 'COST');

  SELECT CONFIG_VALUE::NUMBER INTO :V_DAILY_THRESHOLD
  FROM FINOPS_CONFIG
  WHERE MODULE_NAME = 'COST'
    AND CONFIG_KEY = 'DAILY_CREDIT_THRESHOLD'
    AND ENABLED;

  SELECT CONFIG_VALUE::FLOAT INTO :V_GROWTH_THRESHOLD
  FROM FINOPS_CONFIG
  WHERE MODULE_NAME = 'COST'
    AND CONFIG_KEY = 'GROWTH_RATIO_THRESHOLD'
    AND ENABLED;

  SELECT COALESCE(SUM(CREDITS_USED), 0) INTO :V_CURRENT_CREDITS
  FROM SNOWFLAKE.ACCOUNT_USAGE.METERING_HISTORY
  WHERE TO_DATE(CONVERT_TIMEZONE('UTC', START_TIME)) = :P_ANALYSIS_DATE;

  SELECT SUM(CREDITS_USED) INTO :V_PREVIOUS_CREDITS
  FROM SNOWFLAKE.ACCOUNT_USAGE.METERING_HISTORY
  WHERE TO_DATE(CONVERT_TIMEZONE('UTC', START_TIME)) = DATEADD(DAY, -1, :P_ANALYSIS_DATE);

  V_POLICY := FINOPS_CLASSIFY_COST(
    V_CURRENT_CREDITS,
    V_PREVIOUS_CREDITS,
    V_DAILY_THRESHOLD,
    V_GROWTH_THRESHOLD
  );
  V_STATUS := V_POLICY:status::STRING;
  V_GROWTH_RATIO := V_POLICY:growth_ratio::FLOAT;

  DELETE FROM FINOPS_FINDING
  WHERE RUN_ID = :P_RUN_ID
    AND MODULE_NAME = 'COST'
    AND FINDING_TYPE IN ('DAILY_CREDITS_HIGH', 'DAILY_CREDIT_GROWTH_HIGH');

  IF (V_POLICY:credit_threshold_exceeded::BOOLEAN) THEN
    INSERT INTO FINOPS_FINDING (
      RUN_ID, MODULE_NAME, FINDING_TYPE, SEVERITY,
      METRIC_NAME, METRIC_VALUE, METRIC_UNIT,
      THRESHOLD_VALUE, COMPARISON, DETAILS
    ) VALUES (
      :P_RUN_ID, 'COST', 'DAILY_CREDITS_HIGH', 'WARNING',
      'daily_credits', :V_CURRENT_CREDITS, 'credits',
      :V_DAILY_THRESHOLD, 'GREATER_THAN',
      OBJECT_CONSTRUCT('analysis_date', :P_ANALYSIS_DATE)
    );
  END IF;

  IF (V_POLICY:growth_threshold_exceeded::BOOLEAN) THEN
    INSERT INTO FINOPS_FINDING (
      RUN_ID, MODULE_NAME, FINDING_TYPE, SEVERITY,
      METRIC_NAME, METRIC_VALUE, METRIC_UNIT,
      THRESHOLD_VALUE, COMPARISON, DETAILS
    ) VALUES (
      :P_RUN_ID, 'COST', 'DAILY_CREDIT_GROWTH_HIGH', 'WARNING',
      'day_over_day_growth_ratio', :V_GROWTH_RATIO, 'ratio',
      :V_GROWTH_THRESHOLD, 'GREATER_THAN',
      OBJECT_CONSTRUCT(
        'analysis_date', :P_ANALYSIS_DATE,
        'current_credits', :V_CURRENT_CREDITS,
        'previous_credits', :V_PREVIOUS_CREDITS
      )
    );
  END IF;

  CALL SP_FINOPS_COMPLETE_MODULE(:P_RUN_ID, 'COST', :V_STATUS, :V_POLICY);
  RETURN V_POLICY;
EXCEPTION
  WHEN OTHER THEN
    CALL SP_FINOPS_FAIL_MODULE(:P_RUN_ID, 'COST', SQLCODE::STRING, SQLERRM);
    RAISE;
END;
$$;
