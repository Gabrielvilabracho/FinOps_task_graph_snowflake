USE DATABASE FINOPS_DEV;
USE SCHEMA FINOPS;

CREATE OR REPLACE PROCEDURE SP_FINOPS_CHECK_COST(
  P_RUN_ID STRING,
  P_ANALYSIS_DATE DATE
)
RETURNS OBJECT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  V_WINDOW_START TIMESTAMP_TZ;
  V_WINDOW_END TIMESTAMP_TZ;
  V_EXPECTED_COMPLETE_AT TIMESTAMP_TZ;
  V_SOURCE_WATERMARK TIMESTAMP_LTZ;
  V_SOURCE_ROW_COUNT NUMBER;
  V_KNOWN_COUNT NUMBER;
  V_HISTORY_START TIMESTAMP_LTZ;
  V_PREVIOUS_ROW_COUNT NUMBER;
  V_PREVIOUS_KNOWN_COUNT NUMBER;
  V_PREVIOUS_REASON STRING;
  V_SERVICES ARRAY;
  V_FINANCIAL_ROWS NUMBER DEFAULT 0;
  V_FINANCIAL_KNOWN NUMBER DEFAULT 0;
  V_FINANCIAL_RAW NUMBER(38, 9);
  V_ADJUSTMENT NUMBER(38, 9);
  V_BILLED NUMBER(38, 9);
  V_FINANCIAL_LATEST DATE;
  V_FINANCIAL_FIRST DATE;
  V_FINANCIAL_REASON STRING;
  V_FINANCIAL OBJECT;
  V_SOURCE_TIMEZONE STRING;
  V_PARAMETER_QUERY_ID STRING;
  V_IS_COMPLETE BOOLEAN;
  V_COMPLETENESS_REASON STRING;
  V_CURRENT_RAW NUMBER(38, 9);
  V_CURRENT_CREDITS NUMBER(38, 9);
  V_PREVIOUS_CREDITS NUMBER(38, 9);
  V_DAILY_THRESHOLD NUMBER(38, 9);
  V_GROWTH_THRESHOLD FLOAT;
  V_POLICY OBJECT;
  V_STATUS STRING;
  V_GROWTH_RATIO FLOAT;
BEGIN
  CALL SP_FINOPS_MARK_MODULE_START(:P_RUN_ID, 'COST');

  V_WINDOW_START := TO_TIMESTAMP_TZ(
    TO_CHAR(P_ANALYSIS_DATE, 'YYYY-MM-DD') || ' 00:00:00 +00:00'
  );
  V_WINDOW_END := DATEADD(DAY, 1, V_WINDOW_START);
  V_EXPECTED_COMPLETE_AT := DATEADD(HOUR, FINOPS_METERING_WAIT_HOURS(NULL), V_WINDOW_END);

  SELECT CONFIG_VALUE::NUMBER INTO :V_DAILY_THRESHOLD
  FROM FINOPS_CONFIG
  WHERE MODULE_NAME = 'COST'
    AND CONFIG_KEY = 'DAILY_CREDIT_THRESHOLD'
    AND ENABLED;

  SELECT CONFIG_VALUE::FLOAT INTO :V_GROWTH_THRESHOLD
  FROM FINOPS_CONFIG
  WHERE MODULE_NAME = 'COST'
    AND CONFIG_KEY = 'GROWTH_RATIO_THRESHOLD'
    AND ENABLED;

  SELECT COUNT(*), COUNT(CREDITS_USED), SUM(CREDITS_USED)
  INTO :V_SOURCE_ROW_COUNT, :V_KNOWN_COUNT, :V_CURRENT_RAW
  FROM SNOWFLAKE.ACCOUNT_USAGE.METERING_HISTORY
  WHERE START_TIME >= :V_WINDOW_START AND START_TIME < :V_WINDOW_END;

  SELECT MAX(END_TIME), MIN(START_TIME) INTO :V_SOURCE_WATERMARK, :V_HISTORY_START
  FROM SNOWFLAKE.ACCOUNT_USAGE.METERING_HISTORY;

  V_COMPLETENESS_REASON := FINOPS_EVIDENCE_REASON(
    DATEDIFF(SECOND, V_WINDOW_END, CURRENT_TIMESTAMP()) / 3600.0,
    FINOPS_METERING_WAIT_HOURS(NULL), V_SOURCE_ROW_COUNT, V_KNOWN_COUNT,
    V_HISTORY_START <= V_WINDOW_START
  );
  IF (V_COMPLETENESS_REASON IS NULL AND NOT COALESCE(V_SOURCE_WATERMARK >= V_WINDOW_END, FALSE)) THEN
    V_COMPLETENESS_REASON := 'SOURCE_PUBLICATION_INCOMPLETE';
  END IF;
  V_IS_COMPLETE := CURRENT_TIMESTAMP() >= V_EXPECTED_COMPLETE_AT
    AND V_SOURCE_WATERMARK >= V_WINDOW_END AND V_COMPLETENESS_REASON IS NULL;
  V_IS_COMPLETE := COALESCE(V_IS_COMPLETE, FALSE);

  V_CURRENT_CREDITS := CASE
    WHEN V_IS_COMPLETE THEN COALESCE(V_CURRENT_RAW, 0)
    ELSE NULL
  END;

  SELECT COUNT(*), COUNT(CREDITS_USED), SUM(CREDITS_USED)
  INTO :V_PREVIOUS_ROW_COUNT, :V_PREVIOUS_KNOWN_COUNT, :V_PREVIOUS_CREDITS
  FROM SNOWFLAKE.ACCOUNT_USAGE.METERING_HISTORY
  WHERE START_TIME >= DATEADD(DAY, -1, :V_WINDOW_START)
    AND START_TIME < :V_WINDOW_START;

  V_PREVIOUS_REASON := FINOPS_EVIDENCE_REASON(
    DATEDIFF(SECOND, V_WINDOW_START, CURRENT_TIMESTAMP()) / 3600.0,
    FINOPS_METERING_WAIT_HOURS(NULL), V_PREVIOUS_ROW_COUNT, V_PREVIOUS_KNOWN_COUNT,
    V_HISTORY_START <= DATEADD(DAY, -1, V_WINDOW_START)
  );
  IF (V_PREVIOUS_REASON IS NULL AND NOT COALESCE(V_SOURCE_WATERMARK >= V_WINDOW_START, FALSE)) THEN
    V_PREVIOUS_REASON := 'SOURCE_PUBLICATION_INCOMPLETE';
  END IF;
  V_PREVIOUS_CREDITS := IFF(V_PREVIOUS_REASON IS NULL, V_PREVIOUS_CREDITS, NULL);

  SELECT ARRAY_AGG(OBJECT_CONSTRUCT_KEEP_NULL(
    'service_type', SERVICE_TYPE, 'raw_credits', RAW_CREDITS,
    'publication_wait_hours', FINOPS_METERING_WAIT_HOURS(SERVICE_TYPE),
    'known_rows', KNOWN_ROWS, 'source_rows', SOURCE_ROWS
  )) WITHIN GROUP (ORDER BY SERVICE_TYPE) INTO :V_SERVICES
  FROM (
    SELECT SERVICE_TYPE, SUM(CREDITS_USED) AS RAW_CREDITS,
      COUNT(*) AS SOURCE_ROWS, COUNT(CREDITS_USED) AS KNOWN_ROWS
    FROM SNOWFLAKE.ACCOUNT_USAGE.METERING_HISTORY
    WHERE START_TIME >= :V_WINDOW_START AND START_TIME < :V_WINDOW_END
    GROUP BY SERVICE_TYPE
  );

  -- Optional daily financial representation; lack of access must not erase raw evidence.
  BEGIN
    SHOW PARAMETERS LIKE 'TIMEZONE' IN SESSION;
    V_PARAMETER_QUERY_ID := SQLID;
    SELECT "value" INTO :V_SOURCE_TIMEZONE
    FROM TABLE(RESULT_SCAN(:V_PARAMETER_QUERY_ID)) WHERE "key" = 'TIMEZONE';
    SELECT COUNT(*), COUNT(CASE WHEN CREDITS_BILLED IS NOT NULL
      AND CREDITS_USED IS NOT NULL AND CREDITS_ADJUSTMENT_CLOUD_SERVICES IS NOT NULL THEN 1 END), SUM(CREDITS_USED),
      SUM(CREDITS_ADJUSTMENT_CLOUD_SERVICES), SUM(CREDITS_BILLED)
    INTO :V_FINANCIAL_ROWS, :V_FINANCIAL_KNOWN, :V_FINANCIAL_RAW, :V_ADJUSTMENT, :V_BILLED
    FROM SNOWFLAKE.ACCOUNT_USAGE.METERING_DAILY_HISTORY
    WHERE USAGE_DATE = :P_ANALYSIS_DATE;
    SELECT MIN(USAGE_DATE), MAX(USAGE_DATE) INTO :V_FINANCIAL_FIRST, :V_FINANCIAL_LATEST
    FROM SNOWFLAKE.ACCOUNT_USAGE.METERING_DAILY_HISTORY;
    -- 48h is a local provisional-reconciliation margin, not the source's 3h latency SLA.
    V_FINANCIAL_REASON := COALESCE(
      IFF(COALESCE(V_SOURCE_TIMEZONE, '') = 'UTC', NULL, 'SOURCE_SESSION_NOT_UTC'),
      FINOPS_EVIDENCE_REASON(
      DATEDIFF(SECOND, V_WINDOW_END, CURRENT_TIMESTAMP()) / 3600.0,
      48, V_FINANCIAL_ROWS, V_FINANCIAL_KNOWN, V_FINANCIAL_FIRST < P_ANALYSIS_DATE
    ));
    IF (V_FINANCIAL_REASON IS NULL AND NOT COALESCE(V_FINANCIAL_LATEST > P_ANALYSIS_DATE, FALSE)) THEN
      V_FINANCIAL_REASON := 'SOURCE_PUBLICATION_INCOMPLETE';
    END IF;
  EXCEPTION
    WHEN OTHER THEN
      V_FINANCIAL_REASON := 'SOURCE_UNAVAILABLE';
  END;
  V_FINANCIAL := OBJECT_CONSTRUCT_KEEP_NULL(
    'source', 'SNOWFLAKE.ACCOUNT_USAGE.METERING_DAILY_HISTORY',
    'basis', 'BILLED_CREDITS', 'unit', 'credits', 'not_additive', TRUE,
    'state', IFF(V_FINANCIAL_REASON IS NULL, 'OBSERVED', 'PROVISIONAL_OR_UNKNOWN'),
    'reason', V_FINANCIAL_REASON, 'source_rows', V_FINANCIAL_ROWS,
    'observed_raw_credits', V_FINANCIAL_RAW, 'observed_billed_credits', V_BILLED,
    'observed_cloud_services_adjustment', V_ADJUSTMENT,
    'history_start', V_FINANCIAL_FIRST, 'publication_latency_hours', 3,
    'source_session_timezone', V_SOURCE_TIMEZONE,
    'reconciliation_margin_hours', 48, 'invoice_reconciled', FALSE
  );

  IF (V_IS_COMPLETE) THEN
    V_POLICY := FINOPS_CLASSIFY_COST(
      V_CURRENT_CREDITS,
      V_PREVIOUS_CREDITS,
      V_DAILY_THRESHOLD,
      V_GROWTH_THRESHOLD
    );
    V_STATUS := V_POLICY:status::STRING;
    V_GROWTH_RATIO := V_POLICY:growth_ratio::FLOAT;
  ELSE
    V_STATUS := 'DATA_INCOMPLETE';
    V_GROWTH_RATIO := NULL;
    V_POLICY := OBJECT_CONSTRUCT_KEEP_NULL(
      'status', V_STATUS,
      'current_credits', NULL,
      'previous_credits', NULL,
      'growth_ratio', NULL,
      'daily_credit_threshold', V_DAILY_THRESHOLD,
      'growth_ratio_threshold', V_GROWTH_THRESHOLD,
      'credit_threshold_exceeded', FALSE,
      'growth_threshold_exceeded', FALSE,
      'completeness_reason', V_COMPLETENESS_REASON
    );
  END IF;

  V_POLICY := OBJECT_INSERT(V_POLICY, 'evidence', OBJECT_CONSTRUCT_KEEP_NULL(
    'basis', 'RAW_CONSUMPTION', 'unit', 'credits', 'history_start', V_HISTORY_START,
    'coverage', 'OBSERVED_POPULATION_ONLY', 'invoice_reconciled', FALSE,
    'reason', V_COMPLETENESS_REASON, 'previous_reason', V_PREVIOUS_REASON,
    'services', V_SERVICES, 'financial', V_FINANCIAL,
    'scope_note', 'Credits only; representations overlap. No payable currency or invoice claim.'
  ));

  DELETE FROM FINOPS_FINDING
  WHERE RUN_ID = :P_RUN_ID
    AND MODULE_NAME = 'COST'
    AND FINDING_TYPE IN ('DAILY_CREDITS_HIGH', 'DAILY_CREDIT_GROWTH_HIGH');

  IF (V_POLICY:credit_threshold_exceeded::BOOLEAN) THEN
    INSERT INTO FINOPS_FINDING (
      RUN_ID, MODULE_NAME, FINDING_TYPE, SEVERITY,
      METRIC_NAME, METRIC_VALUE, METRIC_UNIT,
      THRESHOLD_VALUE, COMPARISON, DETAILS
    ) VALUES (
      :P_RUN_ID, 'COST', 'DAILY_CREDITS_HIGH', 'WARNING',
      'daily_credits', :V_CURRENT_CREDITS, 'credits',
      :V_DAILY_THRESHOLD, 'GREATER_THAN',
      OBJECT_CONSTRUCT('analysis_date', :P_ANALYSIS_DATE)
    );
  END IF;

  IF (V_POLICY:growth_threshold_exceeded::BOOLEAN) THEN
    INSERT INTO FINOPS_FINDING (
      RUN_ID, MODULE_NAME, FINDING_TYPE, SEVERITY,
      METRIC_NAME, METRIC_VALUE, METRIC_UNIT,
      THRESHOLD_VALUE, COMPARISON, DETAILS
    ) VALUES (
      :P_RUN_ID, 'COST', 'DAILY_CREDIT_GROWTH_HIGH', 'WARNING',
      'day_over_day_growth_ratio', :V_GROWTH_RATIO, 'ratio',
      :V_GROWTH_THRESHOLD, 'GREATER_THAN',
      OBJECT_CONSTRUCT(
        'analysis_date', :P_ANALYSIS_DATE,
        'current_credits', :V_CURRENT_CREDITS,
        'previous_credits', :V_PREVIOUS_CREDITS
      )
    );
  END IF;

  CALL SP_FINOPS_RECORD_METRIC(
    :P_RUN_ID, 'COST', 'DAILY_CREDITS', :V_STATUS,
    :V_CURRENT_CREDITS, :V_PREVIOUS_CREDITS, NULL, NULL,
    IFF(:V_IS_COMPLETE, :V_CURRENT_CREDITS - :V_PREVIOUS_CREDITS, NULL),
    :V_GROWTH_RATIO, :V_DAILY_THRESHOLD, 'credits', ARRAY_CONSTRUCT(),
    IFF(:V_IS_COMPLETE, 'Raw credits used for the UTC analysis day.',
      'Account Usage data is not complete for the UTC analysis day.'),
    IFF(:V_IS_COMPLETE, 'Review approved cost findings when present.',
      'Rerun after the source is expected to be complete.'),
    'SNOWFLAKE.ACCOUNT_USAGE.METERING_HISTORY',
    :V_WINDOW_START, :V_WINDOW_END, :V_SOURCE_ROW_COUNT,
    :V_SOURCE_WATERMARK, :V_EXPECTED_COMPLETE_AT, :V_IS_COMPLETE,
    :V_COMPLETENESS_REASON
  );

  CALL SP_FINOPS_RECORD_METRIC(
    :P_RUN_ID, 'COST', 'DAY_OVER_DAY_GROWTH_RATIO',
    IFF(:V_PREVIOUS_REASON IS NULL, :V_STATUS, 'DATA_INCOMPLETE'),
    :V_GROWTH_RATIO, NULL, NULL, NULL, NULL, NULL,
    :V_GROWTH_THRESHOLD, 'ratio', ARRAY_CONSTRUCT(),
    'Day-over-day growth in raw credits used.',
    'Investigate the source of growth when the approved threshold is exceeded.',
    'SNOWFLAKE.ACCOUNT_USAGE.METERING_HISTORY',
    :V_WINDOW_START, :V_WINDOW_END, :V_SOURCE_ROW_COUNT,
    :V_SOURCE_WATERMARK, :V_EXPECTED_COMPLETE_AT,
    :V_IS_COMPLETE AND :V_PREVIOUS_REASON IS NULL,
    COALESCE(:V_COMPLETENESS_REASON, :V_PREVIOUS_REASON)
  );

  CALL SP_FINOPS_RECORD_METRIC(
    :P_RUN_ID, 'COST', 'DAILY_BILLED_CREDITS', 'REVIEW_REQUIRED',
    IFF(:V_FINANCIAL_REASON IS NULL, :V_BILLED, NULL),
    NULL, NULL, NULL, NULL, NULL, NULL, 'credits', ARRAY_CONSTRUCT(:V_FINANCIAL),
    'Daily billed credits after adjustment; overlaps raw consumption and is not currency.',
    'Reconcile contractual currency and invoice separately; never sum representations.',
    'SNOWFLAKE.ACCOUNT_USAGE.METERING_DAILY_HISTORY',
    :V_WINDOW_START, :V_WINDOW_END, :V_FINANCIAL_ROWS,
    NULL, DATEADD(HOUR, 48, :V_WINDOW_END), :V_FINANCIAL_REASON IS NULL,
    :V_FINANCIAL_REASON
  );

  CALL SP_FINOPS_COMPLETE_MODULE_FROM_METRICS(:P_RUN_ID, 'COST', :V_POLICY);
  RETURN V_POLICY;
EXCEPTION
  WHEN OTHER THEN
    CALL SP_FINOPS_FAIL_MODULE(:P_RUN_ID, 'COST', SQLCODE::STRING, SQLERRM);
    RAISE;
END;
$$;
