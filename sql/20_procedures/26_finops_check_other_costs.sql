USE DATABASE FINOPS_DEV;
USE SCHEMA FINOPS;

CREATE OR REPLACE PROCEDURE SP_FINOPS_CHECK_OTHER_COSTS(
  P_RUN_ID STRING,
  P_ANALYSIS_DATE DATE
)
RETURNS OBJECT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  V_OTHER_CREDITS NUMBER(38, 9);
  V_SERVICE_TYPE_COUNT NUMBER;
  V_SERVERLESS_TASK_CREDITS NUMBER(38, 9);
  V_METRICS VARIANT;
BEGIN
  CALL SP_FINOPS_MARK_MODULE_START(:P_RUN_ID, 'OTHER_COSTS');

  SELECT
    COALESCE(SUM(IFF(SERVICE_TYPE NOT IN ('WAREHOUSE_METERING', 'AI_SERVICES'), CREDITS_USED, 0)), 0),
    COUNT(DISTINCT IFF(SERVICE_TYPE NOT IN ('WAREHOUSE_METERING', 'AI_SERVICES'), SERVICE_TYPE, NULL)),
    COALESCE(SUM(IFF(SERVICE_TYPE ILIKE '%SERVERLESS_TASK%', CREDITS_USED, 0)), 0)
  INTO :V_OTHER_CREDITS, :V_SERVICE_TYPE_COUNT, :V_SERVERLESS_TASK_CREDITS
  FROM SNOWFLAKE.ACCOUNT_USAGE.METERING_HISTORY
  WHERE TO_DATE(CONVERT_TIMEZONE('UTC', START_TIME)) = :P_ANALYSIS_DATE;

  V_METRICS := OBJECT_CONSTRUCT(
    'analysis_date', P_ANALYSIS_DATE,
    'other_metered_credits', V_OTHER_CREDITS,
    'service_type_count', V_SERVICE_TYPE_COUNT,
    'serverless_task_credits', V_SERVERLESS_TASK_CREDITS,
    'scope_note', 'Currency, storage, and transfer charges require organization billing views and separate privileges.'
  );

  CALL SP_FINOPS_RECORD_RULE_GAP(
    :P_RUN_ID,
    'OTHER_COSTS',
    :V_METRICS,
    'Approve included service types, optional organization-currency scope, and anomaly rules.'
  );
  RETURN V_METRICS;
EXCEPTION
  WHEN OTHER THEN
    CALL SP_FINOPS_FAIL_MODULE(:P_RUN_ID, 'OTHER_COSTS', SQLCODE::STRING, SQLERRM);
    RAISE;
END;
$$;
