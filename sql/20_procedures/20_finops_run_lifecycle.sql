USE DATABASE FINOPS_DEV;
USE SCHEMA FINOPS;

-- Module states: PENDING, RUNNING, NORMAL, REVIEW_REQUIRED, ATTENTION,
-- DATA_INCOMPLETE, RULE_NOT_CONFIGURED (compatibility alias), FAILED.
-- Run states: RUNNING, NORMAL, REVIEW_REQUIRED, ATTENTION_REQUIRED,
-- DATA_INCOMPLETE, FAILED.

CREATE OR REPLACE PROCEDURE SP_FINOPS_BEGIN_RUN(
  P_RUN_ID STRING,
  P_ANALYSIS_DATE DATE,
  P_SCHEDULED_AT TIMESTAMP_LTZ
)
RETURNS OBJECT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  V_DBT_ANALYTICS_ENABLED BOOLEAN DEFAULT FALSE;
BEGIN
  SELECT COALESCE(CONFIG_VALUE::BOOLEAN, FALSE)
    INTO :V_DBT_ANALYTICS_ENABLED
  FROM FINOPS_CONFIG
  WHERE MODULE_NAME = 'DBT_ANALYTICS'
    AND CONFIG_KEY = 'ENABLED'
    AND ENABLED;

  MERGE INTO FINOPS_RUN target
  USING (
    SELECT
      :P_RUN_ID AS RUN_ID,
      :P_ANALYSIS_DATE AS ANALYSIS_DATE,
      :P_SCHEDULED_AT AS SCHEDULED_AT
  ) source
  ON target.RUN_ID = source.RUN_ID
  WHEN MATCHED THEN UPDATE SET
    target.GRAPH_RUN_GROUP_ID = source.RUN_ID,
    target.ANALYSIS_DATE = source.ANALYSIS_DATE,
    target.SCHEDULED_AT = source.SCHEDULED_AT,
    target.STATUS = 'RUNNING',
    target.UPDATED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT (
    RUN_ID, GRAPH_RUN_GROUP_ID, ANALYSIS_DATE, SCHEDULED_AT, STATUS
  ) VALUES (
    source.RUN_ID, source.RUN_ID, source.ANALYSIS_DATE,
    source.SCHEDULED_AT, 'RUNNING'
  );

  MERGE INTO FINOPS_MODULE_RUN target
  USING (
    SELECT :P_RUN_ID AS RUN_ID, COLUMN1::STRING AS MODULE_NAME
    FROM VALUES
      ('COST'),
      ('ERRORS'),
      ('WAREHOUSE'),
      ('QUERIES'),
      ('AI'),
      ('OTHER_COSTS'),
      ('DBT_ANALYTICS')
    WHERE COLUMN1::STRING <> 'DBT_ANALYTICS'
      OR :V_DBT_ANALYTICS_ENABLED
  ) source
  ON target.RUN_ID = source.RUN_ID AND target.MODULE_NAME = source.MODULE_NAME
  WHEN NOT MATCHED THEN INSERT (RUN_ID, MODULE_NAME, STATUS)
    VALUES (source.RUN_ID, source.MODULE_NAME, 'PENDING');

  UPDATE FINOPS_RUN
  SET
    MODULE_COUNT = 6 + IFF(:V_DBT_ANALYTICS_ENABLED, 1, 0),
    UPDATED_AT = CURRENT_TIMESTAMP()
  WHERE RUN_ID = :P_RUN_ID;

  RETURN OBJECT_CONSTRUCT(
    'run_id', P_RUN_ID,
    'analysis_date', P_ANALYSIS_DATE,
    'status', 'RUNNING'
  );
END;
$$;

CREATE OR REPLACE PROCEDURE SP_FINOPS_MARK_MODULE_START(
  P_RUN_ID STRING,
  P_MODULE_NAME STRING
)
RETURNS OBJECT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN
  UPDATE FINOPS_MODULE_RUN
  SET
    STATUS = 'RUNNING',
    STARTED_AT = COALESCE(STARTED_AT, CURRENT_TIMESTAMP()),
    COMPLETED_AT = NULL,
    ERROR_CODE = NULL,
    ERROR_MESSAGE = NULL,
    UPDATED_AT = CURRENT_TIMESTAMP()
  WHERE RUN_ID = :P_RUN_ID AND MODULE_NAME = :P_MODULE_NAME;

  RETURN OBJECT_CONSTRUCT('run_id', P_RUN_ID, 'module', P_MODULE_NAME, 'status', 'RUNNING');
END;
$$;

CREATE OR REPLACE PROCEDURE SP_FINOPS_COMPLETE_MODULE(
  P_RUN_ID STRING,
  P_MODULE_NAME STRING,
  P_STATUS STRING,
  P_METRICS VARIANT
)
RETURNS OBJECT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  V_FINDING_COUNT NUMBER;
BEGIN
  SELECT COUNT(*) INTO :V_FINDING_COUNT
  FROM FINOPS_FINDING
  WHERE RUN_ID = :P_RUN_ID AND MODULE_NAME = :P_MODULE_NAME;

  UPDATE FINOPS_MODULE_RUN
  SET
    STATUS = :P_STATUS,
    COMPLETED_AT = CURRENT_TIMESTAMP(),
    METRICS = :P_METRICS,
    FINDING_COUNT = :V_FINDING_COUNT,
    ERROR_CODE = NULL,
    ERROR_MESSAGE = NULL,
    UPDATED_AT = CURRENT_TIMESTAMP()
  WHERE RUN_ID = :P_RUN_ID AND MODULE_NAME = :P_MODULE_NAME;

  RETURN OBJECT_CONSTRUCT(
    'run_id', P_RUN_ID,
    'module', P_MODULE_NAME,
    'status', P_STATUS,
    'finding_count', V_FINDING_COUNT
  );
END;
$$;

CREATE OR REPLACE PROCEDURE SP_FINOPS_RECORD_METRIC(
  P_RUN_ID STRING,
  P_MODULE_NAME STRING,
  P_METRIC_KEY STRING,
  P_STATUS STRING,
  P_CURRENT_VALUE NUMBER(38, 9),
  P_PREVIOUS_VALUE NUMBER(38, 9),
  P_BASELINE_7D_VALUE NUMBER(38, 9),
  P_BASELINE_30D_VALUE NUMBER(38, 9),
  P_DELTA_ABSOLUTE NUMBER(38, 9),
  P_DELTA_PERCENT NUMBER(38, 9),
  P_THRESHOLD_VALUE NUMBER(38, 9),
  P_METRIC_UNIT STRING,
  P_CONTRIBUTORS VARIANT,
  P_EXPLANATION STRING,
  P_RECOMMENDED_ACTION STRING,
  P_SOURCE_NAME STRING,
  P_SOURCE_WINDOW_START TIMESTAMP_LTZ,
  P_SOURCE_WINDOW_END TIMESTAMP_LTZ,
  P_SOURCE_ROW_COUNT NUMBER,
  P_SOURCE_WATERMARK TIMESTAMP_LTZ,
  P_EXPECTED_COMPLETE_AT TIMESTAMP_LTZ,
  P_IS_COMPLETE BOOLEAN,
  P_COMPLETENESS_REASON STRING
)
RETURNS OBJECT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  V_EFFECTIVE_STATUS STRING;
BEGIN
  V_EFFECTIVE_STATUS := P_STATUS;
  IF (
    NOT P_IS_COMPLETE
    AND FINOPS_STATUS_PRECEDENCE(P_STATUS)
      < FINOPS_STATUS_PRECEDENCE('DATA_INCOMPLETE')
  ) THEN
    V_EFFECTIVE_STATUS := 'DATA_INCOMPLETE';
  END IF;

  MERGE INTO FINOPS_METRIC target
  USING (
    SELECT
      :P_RUN_ID AS RUN_ID, :P_MODULE_NAME AS MODULE_NAME,
      :P_METRIC_KEY AS METRIC_KEY, :V_EFFECTIVE_STATUS AS STATUS,
      :P_CURRENT_VALUE AS CURRENT_VALUE, :P_PREVIOUS_VALUE AS PREVIOUS_VALUE,
      :P_BASELINE_7D_VALUE AS BASELINE_7D_VALUE,
      :P_BASELINE_30D_VALUE AS BASELINE_30D_VALUE,
      :P_DELTA_ABSOLUTE AS DELTA_ABSOLUTE, :P_DELTA_PERCENT AS DELTA_PERCENT,
      :P_THRESHOLD_VALUE AS THRESHOLD_VALUE, :P_METRIC_UNIT AS METRIC_UNIT,
      :P_CONTRIBUTORS AS CONTRIBUTORS, :P_EXPLANATION AS EXPLANATION,
      :P_RECOMMENDED_ACTION AS RECOMMENDED_ACTION, :P_SOURCE_NAME AS SOURCE_NAME,
      :P_SOURCE_WINDOW_START AS SOURCE_WINDOW_START,
      :P_SOURCE_WINDOW_END AS SOURCE_WINDOW_END,
      :P_SOURCE_ROW_COUNT AS SOURCE_ROW_COUNT,
      :P_SOURCE_WATERMARK AS SOURCE_WATERMARK,
      :P_EXPECTED_COMPLETE_AT AS EXPECTED_COMPLETE_AT,
      :P_IS_COMPLETE AS IS_COMPLETE,
      :P_COMPLETENESS_REASON AS COMPLETENESS_REASON
  ) source
  ON target.RUN_ID = source.RUN_ID
    AND target.MODULE_NAME = source.MODULE_NAME
    AND target.METRIC_KEY = source.METRIC_KEY
  WHEN MATCHED THEN UPDATE SET
    target.STATUS = source.STATUS,
    target.CURRENT_VALUE = source.CURRENT_VALUE,
    target.PREVIOUS_VALUE = source.PREVIOUS_VALUE,
    target.BASELINE_7D_VALUE = source.BASELINE_7D_VALUE,
    target.BASELINE_30D_VALUE = source.BASELINE_30D_VALUE,
    target.DELTA_ABSOLUTE = source.DELTA_ABSOLUTE,
    target.DELTA_PERCENT = source.DELTA_PERCENT,
    target.THRESHOLD_VALUE = source.THRESHOLD_VALUE,
    target.METRIC_UNIT = source.METRIC_UNIT,
    target.CONTRIBUTORS = source.CONTRIBUTORS,
    target.EXPLANATION = source.EXPLANATION,
    target.RECOMMENDED_ACTION = source.RECOMMENDED_ACTION,
    target.SOURCE_NAME = source.SOURCE_NAME,
    target.SOURCE_WINDOW_START = source.SOURCE_WINDOW_START,
    target.SOURCE_WINDOW_END = source.SOURCE_WINDOW_END,
    target.SOURCE_ROW_COUNT = source.SOURCE_ROW_COUNT,
    target.SOURCE_WATERMARK = source.SOURCE_WATERMARK,
    target.COLLECTED_AT = CURRENT_TIMESTAMP(),
    target.EXPECTED_COMPLETE_AT = source.EXPECTED_COMPLETE_AT,
    target.IS_COMPLETE = source.IS_COMPLETE,
    target.COMPLETENESS_REASON = source.COMPLETENESS_REASON,
    target.UPDATED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT (
    RUN_ID, MODULE_NAME, METRIC_KEY, STATUS, CURRENT_VALUE, PREVIOUS_VALUE,
    BASELINE_7D_VALUE, BASELINE_30D_VALUE, DELTA_ABSOLUTE, DELTA_PERCENT,
    THRESHOLD_VALUE, METRIC_UNIT, CONTRIBUTORS, EXPLANATION,
    RECOMMENDED_ACTION, SOURCE_NAME, SOURCE_WINDOW_START, SOURCE_WINDOW_END,
    SOURCE_ROW_COUNT, SOURCE_WATERMARK, EXPECTED_COMPLETE_AT, IS_COMPLETE,
    COMPLETENESS_REASON
  ) VALUES (
    source.RUN_ID, source.MODULE_NAME, source.METRIC_KEY, source.STATUS,
    source.CURRENT_VALUE, source.PREVIOUS_VALUE, source.BASELINE_7D_VALUE,
    source.BASELINE_30D_VALUE, source.DELTA_ABSOLUTE, source.DELTA_PERCENT,
    source.THRESHOLD_VALUE, source.METRIC_UNIT, source.CONTRIBUTORS,
    source.EXPLANATION, source.RECOMMENDED_ACTION, source.SOURCE_NAME,
    source.SOURCE_WINDOW_START, source.SOURCE_WINDOW_END,
    source.SOURCE_ROW_COUNT, source.SOURCE_WATERMARK,
    source.EXPECTED_COMPLETE_AT, source.IS_COMPLETE,
    source.COMPLETENESS_REASON
  );

  RETURN OBJECT_CONSTRUCT(
    'run_id', P_RUN_ID, 'module', P_MODULE_NAME,
    'metric_key', P_METRIC_KEY, 'status', V_EFFECTIVE_STATUS,
    'is_complete', P_IS_COMPLETE
  );
END;
$$;

CREATE OR REPLACE PROCEDURE SP_FINOPS_COMPLETE_MODULE_FROM_METRICS(
  P_RUN_ID STRING,
  P_MODULE_NAME STRING,
  P_METRICS VARIANT
)
RETURNS OBJECT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  V_STATUS STRING;
BEGIN
  SELECT STATUS INTO :V_STATUS
  FROM FINOPS_METRIC
  WHERE RUN_ID = :P_RUN_ID AND MODULE_NAME = :P_MODULE_NAME
  ORDER BY FINOPS_STATUS_PRECEDENCE(STATUS) DESC, METRIC_KEY
  LIMIT 1;

  CALL SP_FINOPS_COMPLETE_MODULE(:P_RUN_ID, :P_MODULE_NAME, :V_STATUS, :P_METRICS);

  RETURN OBJECT_CONSTRUCT(
    'run_id', P_RUN_ID, 'module', P_MODULE_NAME, 'status', V_STATUS
  );
END;
$$;

CREATE OR REPLACE PROCEDURE SP_FINOPS_FAIL_MODULE(
  P_RUN_ID STRING,
  P_MODULE_NAME STRING,
  P_ERROR_CODE STRING,
  P_ERROR_MESSAGE STRING
)
RETURNS OBJECT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
BEGIN
  UPDATE FINOPS_MODULE_RUN
  SET
    STATUS = 'FAILED',
    COMPLETED_AT = CURRENT_TIMESTAMP(),
    ERROR_CODE = :P_ERROR_CODE,
    ERROR_MESSAGE = LEFT(:P_ERROR_MESSAGE, 4000),
    UPDATED_AT = CURRENT_TIMESTAMP()
  WHERE RUN_ID = :P_RUN_ID AND MODULE_NAME = :P_MODULE_NAME;

  DELETE FROM FINOPS_FINDING
  WHERE RUN_ID = :P_RUN_ID
    AND MODULE_NAME = :P_MODULE_NAME
    AND FINDING_TYPE = 'TECHNICAL_FAILURE'
    AND METRIC_NAME = 'module_execution';

  INSERT INTO FINOPS_FINDING (
    RUN_ID, MODULE_NAME, FINDING_TYPE, SEVERITY,
    METRIC_NAME, DETAILS
  )
  SELECT
    :P_RUN_ID,
    :P_MODULE_NAME,
    'TECHNICAL_FAILURE',
    'CRITICAL',
    'module_execution',
    OBJECT_CONSTRUCT(
      'error_code', :P_ERROR_CODE,
      'error_message', LEFT(:P_ERROR_MESSAGE, 4000)
    );

  RETURN OBJECT_CONSTRUCT(
    'run_id', P_RUN_ID,
    'module', P_MODULE_NAME,
    'status', 'FAILED'
  );
END;
$$;

CREATE OR REPLACE PROCEDURE SP_FINOPS_RECORD_RULE_GAP(
  P_RUN_ID STRING,
  P_MODULE_NAME STRING,
  P_METRICS VARIANT,
  P_REQUIRED_DECISION STRING
)
RETURNS OBJECT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  V_METRIC_COUNT NUMBER;
BEGIN
  DELETE FROM FINOPS_FINDING
  WHERE RUN_ID = :P_RUN_ID
    AND MODULE_NAME = :P_MODULE_NAME
    AND FINDING_TYPE = 'RULE_NOT_CONFIGURED';

  INSERT INTO FINOPS_FINDING (
    RUN_ID, MODULE_NAME, FINDING_TYPE, SEVERITY,
    METRIC_NAME, DETAILS
  )
  SELECT
    :P_RUN_ID,
    :P_MODULE_NAME,
    'RULE_NOT_CONFIGURED',
    'INFO',
    'alert_rule',
    OBJECT_CONSTRUCT(
      'metrics', :P_METRICS,
      'required_decision', :P_REQUIRED_DECISION
    );

  SELECT COUNT(*) INTO :V_METRIC_COUNT
  FROM FINOPS_METRIC
  WHERE RUN_ID = :P_RUN_ID AND MODULE_NAME = :P_MODULE_NAME;

  IF (V_METRIC_COUNT > 0) THEN
    CALL SP_FINOPS_COMPLETE_MODULE_FROM_METRICS(
      :P_RUN_ID,
      :P_MODULE_NAME,
      :P_METRICS
    );
  ELSE
    CALL SP_FINOPS_COMPLETE_MODULE(
      :P_RUN_ID,
      :P_MODULE_NAME,
      'RULE_NOT_CONFIGURED',
      :P_METRICS
    );
  END IF;

  RETURN OBJECT_CONSTRUCT(
    'run_id', P_RUN_ID,
    'module', P_MODULE_NAME,
    'status', 'RULE_NOT_CONFIGURED',
    'required_decision', P_REQUIRED_DECISION
  );
END;
$$;
