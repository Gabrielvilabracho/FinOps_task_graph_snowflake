USE DATABASE FINOPS_DEV;
USE SCHEMA FINOPS;

CREATE OR REPLACE PROCEDURE SP_FINOPS_CHECK_WAREHOUSE(
  P_RUN_ID STRING,
  P_ANALYSIS_DATE DATE
)
RETURNS OBJECT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  V_WINDOW_START TIMESTAMP_TZ;
  V_WINDOW_END TIMESTAMP_TZ;
  V_EXPECTED_COMPLETE_AT TIMESTAMP_TZ;
  V_SOURCE_WATERMARK TIMESTAMP_LTZ;
  V_SOURCE_ROW_COUNT NUMBER;
  V_KNOWN_COUNT NUMBER;
  V_ATTRIBUTION_KNOWN_COUNT NUMBER;
  V_ATTRIBUTED_CREDITS NUMBER(38, 9);
  V_RESIDUAL NUMBER(38, 9);
  V_HISTORY_START TIMESTAMP_LTZ;
  V_ATTRIBUTION_REASON STRING;
  V_IS_COMPLETE BOOLEAN;
  V_COMPLETENESS_REASON STRING;
  V_WAREHOUSE_COUNT NUMBER;
  V_TOTAL_CREDITS_RAW NUMBER(38, 9);
  V_TOTAL_CREDITS NUMBER(38, 9);
  V_COMPUTE_CREDITS NUMBER(38, 9);
  V_IDLE_CREDITS NUMBER(38, 9);
  V_IDLE_RATIO FLOAT;
  V_METRICS VARIANT;
BEGIN
  CALL SP_FINOPS_MARK_MODULE_START(:P_RUN_ID, 'WAREHOUSE');

  V_WINDOW_START := TO_TIMESTAMP_TZ(
    TO_CHAR(P_ANALYSIS_DATE, 'YYYY-MM-DD') || ' 00:00:00 +00:00'
  );
  V_WINDOW_END := DATEADD(DAY, 1, V_WINDOW_START);
  -- Includes the cloud-services publication window; not a query-level QAS claim.
  V_EXPECTED_COMPLETE_AT := DATEADD(HOUR, 6, V_WINDOW_END);

  SELECT
    COUNT(*),
    COUNT(DISTINCT WAREHOUSE_ID),
    SUM(CREDITS_USED),
    SUM(CREDITS_USED_COMPUTE),
    SUM(CREDITS_ATTRIBUTED_COMPUTE_QUERIES),
    COUNT(CASE WHEN CREDITS_USED IS NOT NULL AND CREDITS_USED_COMPUTE IS NOT NULL THEN 1 END),
    COUNT(CREDITS_ATTRIBUTED_COMPUTE_QUERIES)
  INTO :V_SOURCE_ROW_COUNT, :V_WAREHOUSE_COUNT, :V_TOTAL_CREDITS_RAW,
    :V_COMPUTE_CREDITS, :V_ATTRIBUTED_CREDITS, :V_KNOWN_COUNT, :V_ATTRIBUTION_KNOWN_COUNT
  FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
  WHERE START_TIME >= :V_WINDOW_START AND START_TIME < :V_WINDOW_END;

  SELECT MAX(END_TIME), MIN(START_TIME) INTO :V_SOURCE_WATERMARK, :V_HISTORY_START
  FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY;

  V_COMPLETENESS_REASON := FINOPS_EVIDENCE_REASON(
    DATEDIFF(SECOND, V_WINDOW_END, CURRENT_TIMESTAMP()) / 3600.0,
    6, V_SOURCE_ROW_COUNT, V_KNOWN_COUNT, V_HISTORY_START <= V_WINDOW_START
  );
  IF (V_COMPLETENESS_REASON IS NULL AND NOT COALESCE(V_SOURCE_WATERMARK >= V_WINDOW_END, FALSE)) THEN
    V_COMPLETENESS_REASON := 'SOURCE_PUBLICATION_INCOMPLETE';
  END IF;
  V_IS_COMPLETE := CURRENT_TIMESTAMP() >= V_EXPECTED_COMPLETE_AT
    AND V_SOURCE_WATERMARK >= V_WINDOW_END AND V_COMPLETENESS_REASON IS NULL;
  V_IS_COMPLETE := COALESCE(V_IS_COMPLETE, FALSE);
  V_TOTAL_CREDITS := CASE
    WHEN V_IS_COMPLETE THEN COALESCE(V_TOTAL_CREDITS_RAW, 0)
    ELSE NULL
  END;

  V_ATTRIBUTION_REASON := COALESCE(V_COMPLETENESS_REASON,
    IFF(V_ATTRIBUTION_KNOWN_COUNT = V_SOURCE_ROW_COUNT, NULL, 'ATTRIBUTION_UNAVAILABLE'));
  V_RESIDUAL := IFF(V_IS_COMPLETE, FINOPS_COMPUTE_RESIDUAL(
    V_COMPUTE_CREDITS, V_ATTRIBUTED_CREDITS, V_SOURCE_ROW_COUNT, V_ATTRIBUTION_KNOWN_COUNT
  ), NULL);
  -- Compatibility aliases retain their nonnegative shape, not a claim of proven idle cost.
  V_IDLE_CREDITS := GREATEST(V_RESIDUAL, 0);
  V_IDLE_RATIO := IFF(V_RESIDUAL IS NOT NULL AND V_COMPUTE_CREDITS = 0,
    0, V_IDLE_CREDITS / NULLIF(V_COMPUTE_CREDITS, 0));
  V_METRICS := OBJECT_CONSTRUCT_KEEP_NULL(
    'analysis_date', P_ANALYSIS_DATE,
    'status', IFF(V_IS_COMPLETE, 'REVIEW_REQUIRED', 'DATA_INCOMPLETE'),
    'warehouse_count', IFF(V_IS_COMPLETE, V_WAREHOUSE_COUNT, NULL),
    'warehouse_credits', V_TOTAL_CREDITS,
    'compute_credits', IFF(V_IS_COMPLETE, V_COMPUTE_CREDITS, NULL),
    'estimated_idle_credits', IFF(V_IS_COMPLETE, V_IDLE_CREDITS, NULL),
    'estimated_idle_ratio', V_IDLE_RATIO,
    'compute_residual_credits', V_RESIDUAL,
    'attribution_known_rows', V_ATTRIBUTION_KNOWN_COUNT,
    'source_rows', V_SOURCE_ROW_COUNT,
    'attribution_reason', V_ATTRIBUTION_REASON,
    'ownership_state', 'UNKNOWN',
    'completeness_reason', V_COMPLETENESS_REASON,
    'evidence', OBJECT_CONSTRUCT_KEEP_NULL(
      'basis', 'WAREHOUSE_COMPUTE_RESIDUAL', 'unit', 'credits',
      'history_start', V_HISTORY_START, 'reason', V_ATTRIBUTION_REASON,
      'ownership_state', 'UNKNOWN', 'qas_state', 'NOT_COLLECTED',
      'scope_note', 'Signed compute less attributed compute. Legacy idle aliases are not waste or savings.'
    )
  );

  CALL SP_FINOPS_RECORD_METRIC(
    :P_RUN_ID, 'WAREHOUSE', 'COMPUTE_RESIDUAL_CREDITS', 'REVIEW_REQUIRED',
    :V_RESIDUAL, NULL, NULL, NULL, NULL, NULL, NULL, 'credits', ARRAY_CONSTRUCT()::VARIANT,
    'Signed warehouse compute residual; excludes cloud services and QAS. Not proven waste.',
    'Approve effective-dated ownership and exclusions before business allocation or actions.',
    'SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY',
    :V_WINDOW_START::TIMESTAMP_LTZ, :V_WINDOW_END::TIMESTAMP_LTZ, :V_SOURCE_ROW_COUNT,
    :V_SOURCE_WATERMARK, :V_EXPECTED_COMPLETE_AT::TIMESTAMP_LTZ, :V_ATTRIBUTION_REASON IS NULL,
    :V_ATTRIBUTION_REASON
  );

  CALL SP_FINOPS_RECORD_METRIC(
    :P_RUN_ID, 'WAREHOUSE', 'WAREHOUSE_CREDITS',
    IFF(:V_IS_COMPLETE, 'REVIEW_REQUIRED', 'DATA_INCOMPLETE'),
    :V_TOTAL_CREDITS, NULL, NULL, NULL, NULL, NULL, NULL, 'credits',
    ARRAY_CONSTRUCT()::VARIANT,
    IFF(:V_IS_COMPLETE, 'Warehouse credits are informational until a rule is approved.',
      'Account Usage data is not complete for the UTC analysis day.'),
    IFF(:V_IS_COMPLETE, 'Review warehouse evidence without applying an invented threshold.',
      'Rerun after the source is expected to be complete.'),
    'SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY',
    :V_WINDOW_START::TIMESTAMP_LTZ, :V_WINDOW_END::TIMESTAMP_LTZ, :V_SOURCE_ROW_COUNT,
    :V_SOURCE_WATERMARK, :V_EXPECTED_COMPLETE_AT::TIMESTAMP_LTZ, :V_IS_COMPLETE,
    :V_COMPLETENESS_REASON
  );

  IF (V_IS_COMPLETE) THEN
    CALL SP_FINOPS_RECORD_RULE_GAP(
      :P_RUN_ID,
      'WAREHOUSE',
      :V_METRICS,
      'Approve the compute-residual interpretation and warehouse-anomaly rule, including exclusions.'
    );
  ELSE
    CALL SP_FINOPS_COMPLETE_MODULE_FROM_METRICS(
      :P_RUN_ID,
      'WAREHOUSE',
      :V_METRICS
    );
  END IF;
  RETURN V_METRICS;
EXCEPTION
  WHEN OTHER THEN
    CALL SP_FINOPS_FAIL_MODULE(:P_RUN_ID, 'WAREHOUSE', :SQLCODE::STRING, :SQLERRM);
    RAISE;
END;
$$;
