USE DATABASE DATALAB;
USE SCHEMA SPAIN;

CREATE OR REPLACE PROCEDURE SP_FINOPS_CHECK_WAREHOUSE(
  P_RUN_ID STRING,
  P_ANALYSIS_DATE DATE
)
RETURNS OBJECT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  V_WINDOW_START TIMESTAMP_TZ;
  V_WINDOW_END TIMESTAMP_TZ;
  V_EXPECTED_COMPLETE_AT TIMESTAMP_TZ;
  V_SOURCE_WATERMARK TIMESTAMP_LTZ;
  V_SOURCE_ROW_COUNT NUMBER;
  V_IS_COMPLETE BOOLEAN;
  V_COMPLETENESS_REASON STRING;
  V_WAREHOUSE_COUNT NUMBER;
  V_TOTAL_CREDITS_RAW NUMBER(38, 9);
  V_TOTAL_CREDITS NUMBER(38, 9);
  V_COMPUTE_CREDITS NUMBER(38, 9);
  V_IDLE_CREDITS NUMBER(38, 9);
  V_IDLE_RATIO FLOAT;
  V_METRICS VARIANT;
BEGIN
  CALL SP_FINOPS_MARK_MODULE_START(:P_RUN_ID, 'WAREHOUSE');

  V_WINDOW_START := TO_TIMESTAMP_TZ(
    TO_CHAR(P_ANALYSIS_DATE, 'YYYY-MM-DD') || ' 00:00:00 +00:00'
  );
  V_WINDOW_END := DATEADD(DAY, 1, V_WINDOW_START);
  V_EXPECTED_COMPLETE_AT := DATEADD(HOUR, 3, V_WINDOW_END);

  SELECT
    COUNT(*),
    COUNT(DISTINCT WAREHOUSE_NAME),
    SUM(CREDITS_USED),
    COALESCE(SUM(CREDITS_USED_COMPUTE), 0),
    GREATEST(
      COALESCE(SUM(CREDITS_USED_COMPUTE), 0)
        - COALESCE(SUM(CREDITS_ATTRIBUTED_COMPUTE_QUERIES), 0),
      0
    )
  INTO :V_SOURCE_ROW_COUNT, :V_WAREHOUSE_COUNT, :V_TOTAL_CREDITS_RAW,
    :V_COMPUTE_CREDITS, :V_IDLE_CREDITS
  FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
  WHERE START_TIME >= :V_WINDOW_START AND START_TIME < :V_WINDOW_END;

  SELECT MAX(END_TIME) INTO :V_SOURCE_WATERMARK
  FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY;

  V_IS_COMPLETE := CURRENT_TIMESTAMP() >= V_EXPECTED_COMPLETE_AT
    AND V_SOURCE_WATERMARK >= V_WINDOW_END;
  V_COMPLETENESS_REASON := CASE
    WHEN CURRENT_TIMESTAMP() < V_EXPECTED_COMPLETE_AT
      THEN 'SOURCE_NOT_EXPECTED_COMPLETE'
    WHEN V_SOURCE_WATERMARK IS NULL
      THEN 'SOURCE_PUBLICATION_ABSENT'
    WHEN V_SOURCE_WATERMARK < V_WINDOW_END
      THEN 'SOURCE_PUBLICATION_INCOMPLETE'
    ELSE NULL
  END;
  V_TOTAL_CREDITS := CASE
    WHEN V_IS_COMPLETE THEN COALESCE(V_TOTAL_CREDITS_RAW, 0)
    ELSE NULL
  END;

  V_IDLE_RATIO := IFF(
    V_IS_COMPLETE AND V_COMPUTE_CREDITS > 0,
    V_IDLE_CREDITS / V_COMPUTE_CREDITS,
    IFF(V_IS_COMPLETE, 0, NULL)
  );
  V_METRICS := OBJECT_CONSTRUCT_KEEP_NULL(
    'analysis_date', P_ANALYSIS_DATE,
    'status', IFF(V_IS_COMPLETE, 'REVIEW_REQUIRED', 'DATA_INCOMPLETE'),
    'warehouse_count', IFF(V_IS_COMPLETE, V_WAREHOUSE_COUNT, NULL),
    'warehouse_credits', V_TOTAL_CREDITS,
    'compute_credits', IFF(V_IS_COMPLETE, V_COMPUTE_CREDITS, NULL),
    'estimated_idle_credits', IFF(V_IS_COMPLETE, V_IDLE_CREDITS, NULL),
    'estimated_idle_ratio', V_IDLE_RATIO,
    'completeness_reason', V_COMPLETENESS_REASON
  );

  CALL SP_FINOPS_RECORD_METRIC(
    :P_RUN_ID, 'WAREHOUSE', 'WAREHOUSE_CREDITS',
    IFF(:V_IS_COMPLETE, 'REVIEW_REQUIRED', 'DATA_INCOMPLETE'),
    :V_TOTAL_CREDITS, NULL, NULL, NULL, NULL, NULL, NULL, 'credits',
    ARRAY_CONSTRUCT(),
    IFF(:V_IS_COMPLETE, 'Warehouse credits are informational until a rule is approved.',
      'Account Usage data is not complete for the UTC analysis day.'),
    IFF(:V_IS_COMPLETE, 'Review warehouse evidence without applying an invented threshold.',
      'Rerun after the source is expected to be complete.'),
    'SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY',
    :V_WINDOW_START, :V_WINDOW_END, :V_SOURCE_ROW_COUNT,
    :V_SOURCE_WATERMARK, :V_EXPECTED_COMPLETE_AT, :V_IS_COMPLETE,
    :V_COMPLETENESS_REASON
  );

  IF (V_IS_COMPLETE) THEN
    CALL SP_FINOPS_RECORD_RULE_GAP(
      :P_RUN_ID,
      'WAREHOUSE',
      :V_METRICS,
      'Approve the idle-credit and warehouse-anomaly rule, including exclusions.'
    );
  ELSE
    CALL SP_FINOPS_COMPLETE_MODULE_FROM_METRICS(
      :P_RUN_ID,
      'WAREHOUSE',
      :V_METRICS
    );
  END IF;
  RETURN V_METRICS;
EXCEPTION
  WHEN OTHER THEN
    CALL SP_FINOPS_FAIL_MODULE(:P_RUN_ID, 'WAREHOUSE', SQLCODE::STRING, SQLERRM);
    RAISE;
END;
$$;
