USE DATABASE FINOPS_DEV;
USE SCHEMA FINOPS;

CREATE OR REPLACE PROCEDURE SP_FINOPS_CHECK_AI(
  P_RUN_ID STRING,
  P_ANALYSIS_DATE DATE
)
RETURNS OBJECT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  V_WINDOW_START TIMESTAMP_TZ;
  V_WINDOW_END TIMESTAMP_TZ;
  V_SOURCE_ROWS NUMBER;
  V_KNOWN_ROWS NUMBER;
  V_UNFINISHED_ROWS NUMBER;
  V_HISTORY_START TIMESTAMP_LTZ;
  V_COMPLETENESS_REASON STRING;
  V_AI_OBSERVED NUMBER(38, 9);
  V_AI_CREDITS NUMBER(38, 9);
  V_QUERY_COUNT NUMBER;
  V_FUNCTION_COUNT NUMBER;
  V_MODEL_COUNT NUMBER;
  V_USER_ROWS NUMBER DEFAULT 0;
  V_USER_KNOWN NUMBER DEFAULT 0;
  V_USER_OBSERVED NUMBER(38, 9);
  V_USER_HISTORY_START TIMESTAMP_LTZ;
  V_USER_REASON STRING;
  V_USER_SERVICES ARRAY DEFAULT ARRAY_CONSTRUCT();
  V_COVERAGE ARRAY;
  V_METRICS VARIANT;
BEGIN
  CALL SP_FINOPS_MARK_MODULE_START(:P_RUN_ID, 'AI');

  V_WINDOW_START := TO_TIMESTAMP_TZ(
    TO_CHAR(P_ANALYSIS_DATE, 'YYYY-MM-DD') || ' 00:00:00 +00:00'
  );
  V_WINDOW_END := DATEADD(DAY, 1, V_WINDOW_START);

  -- A query can span hours/days: keep all usage rows, join one terminal marker per query.
  WITH completed_queries AS (
    SELECT QUERY_ID
    FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AI_FUNCTIONS_USAGE_HISTORY
    WHERE IS_COMPLETED
    GROUP BY QUERY_ID
  )
  SELECT
    SUM(usage.CREDITS), COUNT(*), COUNT(usage.CREDITS),
    COUNT(CASE WHEN completed_queries.QUERY_ID IS NULL THEN 1 END),
    COUNT(DISTINCT usage.QUERY_ID), COUNT(DISTINCT usage.FUNCTION_NAME),
    COUNT(DISTINCT usage.MODEL_NAME)
  INTO :V_AI_OBSERVED, :V_SOURCE_ROWS, :V_KNOWN_ROWS, :V_UNFINISHED_ROWS,
    :V_QUERY_COUNT, :V_FUNCTION_COUNT, :V_MODEL_COUNT
  FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AI_FUNCTIONS_USAGE_HISTORY usage
  LEFT JOIN completed_queries ON usage.QUERY_ID = completed_queries.QUERY_ID
  WHERE usage.START_TIME >= :V_WINDOW_START AND usage.START_TIME < :V_WINDOW_END;

  SELECT MIN(START_TIME) INTO :V_HISTORY_START
  FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AI_FUNCTIONS_USAGE_HISTORY;
  V_COMPLETENESS_REASON := COALESCE(FINOPS_EVIDENCE_REASON(
    DATEDIFF(SECOND, V_WINDOW_END, CURRENT_TIMESTAMP()) / 3600.0,
    5.0 / 60, V_SOURCE_ROWS, V_KNOWN_ROWS,
    P_ANALYSIS_DATE >= '2026-01-05'::DATE AND V_HISTORY_START <= V_WINDOW_START
  ), IFF(V_UNFINISHED_ROWS > 0, 'IN_PROGRESS_QUERIES', NULL));
  V_AI_CREDITS := IFF(V_COMPLETENESS_REASON IS NULL, V_AI_OBSERVED, NULL);

  -- Broader optional subset, aggregated only by service; never read/export user identities.
  BEGIN
    SELECT COUNT(*), COUNT(CREDITS), SUM(CREDITS)
    INTO :V_USER_ROWS, :V_USER_KNOWN, :V_USER_OBSERVED
    FROM SNOWFLAKE.ACCOUNT_USAGE.USER_AI_USAGE_HISTORY
    WHERE USAGE_HOUR >= :V_WINDOW_START AND USAGE_HOUR < :V_WINDOW_END;
    SELECT MIN(USAGE_HOUR) INTO :V_USER_HISTORY_START
    FROM SNOWFLAKE.ACCOUNT_USAGE.USER_AI_USAGE_HISTORY;
    V_USER_REASON := FINOPS_EVIDENCE_REASON(
      DATEDIFF(SECOND, V_WINDOW_END, CURRENT_TIMESTAMP()) / 3600.0,
      1, V_USER_ROWS, V_USER_KNOWN,
      P_ANALYSIS_DATE >= '2026-03-01'::DATE AND V_USER_HISTORY_START <= V_WINDOW_START
    );
    SELECT ARRAY_AGG(OBJECT_CONSTRUCT_KEEP_NULL(
      'service_type', SERVICE_TYPE, 'observed_credits', OBSERVED_CREDITS,
      'source_rows', SOURCE_ROWS, 'known_rows', KNOWN_ROWS,
      'not_additive', TRUE, 'credit_family', 'UNKNOWN'
    )) WITHIN GROUP (ORDER BY SERVICE_TYPE) INTO :V_USER_SERVICES
    FROM (
      SELECT SERVICE_TYPE, SUM(CREDITS) AS OBSERVED_CREDITS,
        COUNT(*) AS SOURCE_ROWS, COUNT(CREDITS) AS KNOWN_ROWS
      FROM SNOWFLAKE.ACCOUNT_USAGE.USER_AI_USAGE_HISTORY
      WHERE USAGE_HOUR >= :V_WINDOW_START AND USAGE_HOUR < :V_WINDOW_END
      GROUP BY SERVICE_TYPE
    );
  EXCEPTION
    WHEN OTHER THEN
      V_USER_REASON := 'SOURCE_UNAVAILABLE';
  END;

  V_COVERAGE := ARRAY_CONSTRUCT(
    OBJECT_CONSTRUCT('entry_point', 'SQL_FUNCTIONS', 'source', 'CORTEX_AI_FUNCTIONS_USAGE_HISTORY',
      'collection', 'COLLECTED', 'history_since', '2026-01-05'),
    OBJECT_CONSTRUCT('entry_point', 'USER_AI_SERVICE_SUBSET', 'source', 'USER_AI_USAGE_HISTORY',
      'collection', IFF(V_USER_REASON = 'SOURCE_UNAVAILABLE', 'UNAVAILABLE', 'COLLECTED'),
      'history_since', '2026-03-01'),
    OBJECT_CONSTRUCT('entry_point', 'AISQL_ALTERNATIVE', 'collection', 'NOT_COLLECTED',
      'overlap', 'SQL_FUNCTIONS'),
    OBJECT_CONSTRUCT('entry_point', 'STANDALONE_ANALYST', 'collection', 'NOT_COLLECTED'),
    OBJECT_CONSTRUCT('entry_point', 'AGENTS_AND_COWORK_DETAIL', 'collection', 'NOT_COLLECTED'),
    OBJECT_CONSTRUCT('entry_point', 'SEARCH_SERVING_AND_EMBEDDING', 'collection', 'NOT_COLLECTED'),
    OBJECT_CONSTRUCT('entry_point', 'GATEWAY_AND_DIRECT_REST_DETAIL', 'collection', 'NOT_COLLECTED'),
    OBJECT_CONSTRUCT('entry_point', 'CONTAINER_WORKLOAD_CLASSIFICATION', 'collection', 'NOT_COLLECTED',
      'scope_note', 'Compute-pool usage is not automatically AI cost.')
  );

  V_METRICS := OBJECT_CONSTRUCT_KEEP_NULL(
    'analysis_date', P_ANALYSIS_DATE,
    'cortex_ai_function_credits', V_AI_CREDITS,
    'query_count', V_QUERY_COUNT,
    'function_count', V_FUNCTION_COUNT,
    'model_count', V_MODEL_COUNT,
    'scope_note', 'Functions detail plus a service-labelled AI subset; not all AI expense.',
    'evidence', OBJECT_CONSTRUCT_KEEP_NULL(
      'basis', 'AI_SERVICE_DETAIL', 'unit', 'credits', 'not_additive', TRUE,
      'reason', V_COMPLETENESS_REASON, 'observed_ai_function_credits', V_AI_OBSERVED,
      'source_rows', V_SOURCE_ROWS, 'known_rows', V_KNOWN_ROWS,
      'history_start', V_HISTORY_START, 'unfinished_rows', V_UNFINISHED_ROWS,
      'user_ai_reason', V_USER_REASON, 'observed_user_ai_credits', V_USER_OBSERVED,
      'user_ai_history_start', V_USER_HISTORY_START, 'services', V_USER_SERVICES,
      'coverage', V_COVERAGE,
      'scope_note', 'Functions, user AI, COST and OTHER_COSTS may overlap. Warehouse credits excluded; no AI grand total.'
    )
  );

  CALL SP_FINOPS_RECORD_METRIC(
    :P_RUN_ID, 'AI', 'CORTEX_AI_FUNCTION_CREDITS', 'REVIEW_REQUIRED',
    :V_AI_CREDITS, NULL, NULL, NULL, NULL, NULL, NULL, 'credits', ARRAY_CONSTRUCT(),
    'Functions-only detail; incomplete or empty publication is not zero.',
    'Approve AI scope and policy independently of source publication.',
    'SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AI_FUNCTIONS_USAGE_HISTORY',
    :V_WINDOW_START, :V_WINDOW_END, :V_SOURCE_ROWS, NULL,
    DATEADD(MINUTE, 5, :V_WINDOW_END), :V_COMPLETENESS_REASON IS NULL, :V_COMPLETENESS_REASON
  );
  CALL SP_FINOPS_RECORD_METRIC(
    :P_RUN_ID, 'AI', 'USER_AI_SUBSET_CREDITS', 'REVIEW_REQUIRED',
    IFF(:V_USER_REASON IS NULL, :V_USER_OBSERVED, NULL),
    NULL, NULL, NULL, NULL, NULL, NULL, 'credits', :V_USER_SERVICES,
    'Covered AI services only; overlaps Functions and account-level metering.',
    'Do not sum representations or infer ownership from user attribution.',
    'SNOWFLAKE.ACCOUNT_USAGE.USER_AI_USAGE_HISTORY',
    :V_WINDOW_START, :V_WINDOW_END, :V_USER_ROWS, NULL,
    DATEADD(HOUR, 1, :V_WINDOW_END), :V_USER_REASON IS NULL, :V_USER_REASON
  );

  CALL SP_FINOPS_RECORD_RULE_GAP(
    :P_RUN_ID,
    'AI',
    :V_METRICS,
    'Approve the AI products in scope, credit rule, exclusions, and severity.'
  );
  RETURN V_METRICS;
EXCEPTION
  WHEN OTHER THEN
    CALL SP_FINOPS_FAIL_MODULE(:P_RUN_ID, 'AI', SQLCODE::STRING, SQLERRM);
    RAISE;
END;
$$;
