USE DATABASE FINOPS_DEV;
USE SCHEMA FINOPS;

CREATE OR REPLACE PROCEDURE SP_FINOPS_CHECK_AI(
  P_RUN_ID STRING,
  P_ANALYSIS_DATE DATE
)
RETURNS OBJECT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  V_AI_CREDITS NUMBER(38, 9);
  V_QUERY_COUNT NUMBER;
  V_FUNCTION_COUNT NUMBER;
  V_MODEL_COUNT NUMBER;
  V_METRICS VARIANT;
BEGIN
  CALL SP_FINOPS_MARK_MODULE_START(:P_RUN_ID, 'AI');

  SELECT
    COALESCE(SUM(CREDITS), 0),
    COUNT(DISTINCT QUERY_ID),
    COUNT(DISTINCT FUNCTION_NAME),
    COUNT(DISTINCT MODEL_NAME)
  INTO :V_AI_CREDITS, :V_QUERY_COUNT, :V_FUNCTION_COUNT, :V_MODEL_COUNT
  FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AI_FUNCTIONS_USAGE_HISTORY
  WHERE TO_DATE(CONVERT_TIMEZONE('UTC', START_TIME)) = :P_ANALYSIS_DATE;

  V_METRICS := OBJECT_CONSTRUCT(
    'analysis_date', P_ANALYSIS_DATE,
    'cortex_ai_function_credits', V_AI_CREDITS,
    'query_count', V_QUERY_COUNT,
    'function_count', V_FUNCTION_COUNT,
    'model_count', V_MODEL_COUNT,
    'scope_note', 'This module covers Cortex AI functions represented by the source view.'
  );

  CALL SP_FINOPS_RECORD_RULE_GAP(
    :P_RUN_ID,
    'AI',
    :V_METRICS,
    'Approve the AI products in scope, credit rule, exclusions, and severity.'
  );
  RETURN V_METRICS;
EXCEPTION
  WHEN OTHER THEN
    CALL SP_FINOPS_FAIL_MODULE(:P_RUN_ID, 'AI', SQLCODE::STRING, SQLERRM);
    RAISE;
END;
$$;
