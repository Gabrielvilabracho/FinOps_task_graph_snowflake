USE DATABASE DATALAB;
USE SCHEMA SPAIN;

-- One rank function drives metric-to-module and module-to-run folding.
-- RULE_NOT_CONFIGURED is retained as a compatibility alias for REVIEW_REQUIRED.
CREATE OR REPLACE FUNCTION FINOPS_STATUS_PRECEDENCE(P_STATUS STRING)
RETURNS NUMBER
LANGUAGE SQL
IMMUTABLE
AS
$$
  CASE UPPER(P_STATUS)
    WHEN 'FAILED' THEN 5
    WHEN 'DATA_INCOMPLETE' THEN 4
    WHEN 'ATTENTION' THEN 3
    WHEN 'ATTENTION_REQUIRED' THEN 3
    WHEN 'REVIEW_REQUIRED' THEN 2
    WHEN 'RULE_NOT_CONFIGURED' THEN 2
    WHEN 'NORMAL' THEN 1
    ELSE 0
  END
$$;
