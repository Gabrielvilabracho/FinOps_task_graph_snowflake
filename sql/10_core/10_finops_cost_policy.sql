USE DATABASE FINOPS_DEV;
USE SCHEMA FINOPS;

CREATE OR REPLACE FUNCTION FINOPS_CLASSIFY_COST(
  CURRENT_CREDITS NUMBER,
  PREVIOUS_CREDITS NUMBER,
  DAILY_CREDIT_THRESHOLD NUMBER,
  GROWTH_RATIO_THRESHOLD FLOAT
)
RETURNS OBJECT
LANGUAGE SQL
IMMUTABLE
AS
$$
  OBJECT_CONSTRUCT_KEEP_NULL(
    'status', IFF(
      CURRENT_CREDITS > DAILY_CREDIT_THRESHOLD
      OR (
        PREVIOUS_CREDITS > 0
        AND ((CURRENT_CREDITS - PREVIOUS_CREDITS) / PREVIOUS_CREDITS) > GROWTH_RATIO_THRESHOLD
      ),
      'ATTENTION',
      'NORMAL'
    ),
    'current_credits', CURRENT_CREDITS,
    'previous_credits', PREVIOUS_CREDITS,
    'growth_ratio', IFF(
      PREVIOUS_CREDITS > 0,
      (CURRENT_CREDITS - PREVIOUS_CREDITS) / PREVIOUS_CREDITS,
      NULL
    ),
    'daily_credit_threshold', DAILY_CREDIT_THRESHOLD,
    'growth_ratio_threshold', GROWTH_RATIO_THRESHOLD,
    'credit_threshold_exceeded', CURRENT_CREDITS > DAILY_CREDIT_THRESHOLD,
    'growth_threshold_exceeded', IFF(
      PREVIOUS_CREDITS > 0,
      ((CURRENT_CREDITS - PREVIOUS_CREDITS) / PREVIOUS_CREDITS) > GROWTH_RATIO_THRESHOLD,
      FALSE
    )
  )
$$;

-- Confirmed default policy: 25 credits and 30 percent growth.
CREATE OR REPLACE FUNCTION FINOPS_CLASSIFY_COST(
  CURRENT_CREDITS NUMBER,
  PREVIOUS_CREDITS NUMBER
)
RETURNS OBJECT
LANGUAGE SQL
IMMUTABLE
AS
$$
  FINOPS_CLASSIFY_COST(CURRENT_CREDITS, PREVIOUS_CREDITS, 25, 0.30)
$$;

-- Publication is evidence, not invoice approval. Sparse/empty history never proves zero.
CREATE OR REPLACE FUNCTION FINOPS_EVIDENCE_REASON(
  AGE_HOURS FLOAT,
  WAIT_HOURS FLOAT,
  SOURCE_ROWS NUMBER,
  KNOWN_ROWS NUMBER,
  HISTORY_COVERED BOOLEAN
)
RETURNS STRING
LANGUAGE SQL
IMMUTABLE
AS
$$
  CASE
    WHEN AGE_HOURS IS NULL OR WAIT_HOURS IS NULL OR AGE_HOURS < WAIT_HOURS
      THEN 'SOURCE_NOT_EXPECTED_COMPLETE'
    WHEN NOT COALESCE(HISTORY_COVERED, FALSE) THEN 'HISTORY_NOT_COVERED'
    WHEN COALESCE(SOURCE_ROWS, 0) = 0 THEN 'SOURCE_PUBLICATION_ABSENT'
    WHEN KNOWN_ROWS IS NULL OR KNOWN_ROWS <> SOURCE_ROWS THEN 'SOURCE_VALUES_INCOMPLETE'
    ELSE NULL
  END
$$;

-- Raw totals include cloud services (up to 6h); Streaming can take 12h.
-- NULL requests a conservative account-wide wait, including absent service populations.
CREATE OR REPLACE FUNCTION FINOPS_METERING_WAIT_HOURS(SERVICE_TYPE STRING)
RETURNS NUMBER
LANGUAGE SQL
IMMUTABLE
AS
$$
  CASE WHEN SERVICE_TYPE IS NULL OR SERVICE_TYPE = 'SNOWPIPE_STREAMING' THEN 12 ELSE 6 END
$$;

-- Signed technical reconciliation only; never an ownership, waste or savings verdict.
CREATE OR REPLACE FUNCTION FINOPS_COMPUTE_RESIDUAL(
  COMPUTE_CREDITS NUMBER(38, 9),
  ATTRIBUTED_CREDITS NUMBER(38, 9),
  SOURCE_ROWS NUMBER,
  KNOWN_ROWS NUMBER
)
RETURNS NUMBER(38, 9)
LANGUAGE SQL
IMMUTABLE
AS
$$
  CASE
    WHEN SOURCE_ROWS > 0 AND KNOWN_ROWS = SOURCE_ROWS
      AND COMPUTE_CREDITS IS NOT NULL AND ATTRIBUTED_CREDITS IS NOT NULL
      THEN COMPUTE_CREDITS - ATTRIBUTED_CREDITS
    ELSE NULL
  END
$$;
