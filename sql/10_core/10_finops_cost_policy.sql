USE DATABASE FINOPS_DEV;
USE SCHEMA FINOPS;

CREATE OR REPLACE FUNCTION FINOPS_CLASSIFY_COST(
  CURRENT_CREDITS NUMBER,
  PREVIOUS_CREDITS NUMBER,
  DAILY_CREDIT_THRESHOLD NUMBER,
  GROWTH_RATIO_THRESHOLD FLOAT
)
RETURNS OBJECT
LANGUAGE SQL
IMMUTABLE
AS
$$
  OBJECT_CONSTRUCT_KEEP_NULL(
    'status', IFF(
      CURRENT_CREDITS > DAILY_CREDIT_THRESHOLD
      OR (
        PREVIOUS_CREDITS > 0
        AND ((CURRENT_CREDITS - PREVIOUS_CREDITS) / PREVIOUS_CREDITS) > GROWTH_RATIO_THRESHOLD
      ),
      'ATTENTION',
      'NORMAL'
    ),
    'current_credits', CURRENT_CREDITS,
    'previous_credits', PREVIOUS_CREDITS,
    'growth_ratio', IFF(
      PREVIOUS_CREDITS > 0,
      (CURRENT_CREDITS - PREVIOUS_CREDITS) / PREVIOUS_CREDITS,
      NULL
    ),
    'daily_credit_threshold', DAILY_CREDIT_THRESHOLD,
    'growth_ratio_threshold', GROWTH_RATIO_THRESHOLD,
    'credit_threshold_exceeded', CURRENT_CREDITS > DAILY_CREDIT_THRESHOLD,
    'growth_threshold_exceeded', IFF(
      PREVIOUS_CREDITS > 0,
      ((CURRENT_CREDITS - PREVIOUS_CREDITS) / PREVIOUS_CREDITS) > GROWTH_RATIO_THRESHOLD,
      FALSE
    )
  )
$$;

-- Confirmed default policy: 25 credits and 30 percent growth.
CREATE OR REPLACE FUNCTION FINOPS_CLASSIFY_COST(
  CURRENT_CREDITS NUMBER,
  PREVIOUS_CREDITS NUMBER
)
RETURNS OBJECT
LANGUAGE SQL
IMMUTABLE
AS
$$
  FINOPS_CLASSIFY_COST(CURRENT_CREDITS, PREVIOUS_CREDITS, 25, 0.30)
$$;
