USE DATABASE FINOPS_DEV;
USE SCHEMA FINOPS;

SELECT SYSTEM$ASSERT_TRUE(
  FINOPS_STATUS_PRECEDENCE('FAILED')
    > FINOPS_STATUS_PRECEDENCE('DATA_INCOMPLETE'),
  'FAILED must outrank DATA_INCOMPLETE.'
);
SELECT SYSTEM$ASSERT_TRUE(
  FINOPS_STATUS_PRECEDENCE('DATA_INCOMPLETE')
    > FINOPS_STATUS_PRECEDENCE('ATTENTION'),
  'DATA_INCOMPLETE must outrank ATTENTION.'
);
SELECT SYSTEM$ASSERT_TRUE(
  FINOPS_STATUS_PRECEDENCE('ATTENTION')
    > FINOPS_STATUS_PRECEDENCE('REVIEW_REQUIRED'),
  'ATTENTION must outrank REVIEW_REQUIRED.'
);
SELECT SYSTEM$ASSERT_TRUE(
  FINOPS_STATUS_PRECEDENCE('REVIEW_REQUIRED')
    > FINOPS_STATUS_PRECEDENCE('NORMAL'),
  'REVIEW_REQUIRED must outrank NORMAL.'
);
SELECT SYSTEM$ASSERT_EQUALS(
  FINOPS_STATUS_PRECEDENCE('REVIEW_REQUIRED'),
  FINOPS_STATUS_PRECEDENCE('RULE_NOT_CONFIGURED'),
  'Legacy rule gaps must fold as review-required.'
);
