-- Run with FINOPS_TASK_OWNER after deployment. No email or historical writes.
USE DATABASE FINOPS_DEV;
USE SCHEMA FINOPS;

EXECUTE IMMEDIATE $$
DECLARE
  V_RUN_ID STRING DEFAULT UUID_STRING();
  V_RESULT OBJECT;
  V_LINES STRING;
  V_COUNT NUMBER;
  V_ERROR_CODE STRING;
  V_ERROR_MESSAGE STRING;
  V_VALUE NUMBER(38, 9);
  V_RATIO NUMBER(38, 9);
  E_EXPECTED EXCEPTION (-20060, 'Expected native diagnostic fixture.');
  E_ASSERT EXCEPTION (-20061, 'Native runtime regression assertion failed.');
BEGIN
  BEGIN TRANSACTION;
  CALL SP_FINOPS_BEGIN_RUN(:V_RUN_ID, CURRENT_DATE(), CURRENT_TIMESTAMP());

  CALL SP_FINOPS_RECORD_METRIC(
    :V_RUN_ID, 'COST', 'NATIVE_FRACTION', 'NORMAL',
    0.125, NULL, NULL, NULL, NULL, 0.30, 25, 'credits', ARRAY_CONSTRUCT()::VARIANT,
    'Fractional native API fixture.', 'No operational action.', 'NATIVE_FIXTURE',
    CURRENT_TIMESTAMP()::TIMESTAMP_LTZ, CURRENT_TIMESTAMP()::TIMESTAMP_LTZ,
    1, CURRENT_TIMESTAMP()::TIMESTAMP_LTZ, CURRENT_TIMESTAMP()::TIMESTAMP_LTZ, TRUE, NULL
  );
  SELECT CURRENT_VALUE, DELTA_PERCENT INTO :V_VALUE, :V_RATIO
  FROM FINOPS_METRIC WHERE RUN_ID = :V_RUN_ID AND METRIC_KEY = 'NATIVE_FRACTION';
  IF (V_VALUE <> 0.125 OR V_RATIO <> 0.30) THEN RAISE E_ASSERT; END IF;
  IF (FINOPS_CLASSIFY_COST(25.001, 25):status::STRING <> 'ATTENTION'
      OR FINOPS_CLASSIFY_COST(13.001, 10, 25, 0.30):status::STRING <> 'ATTENTION'
      OR FINOPS_CLASSIFY_COST(13, 10):status::STRING <> 'NORMAL') THEN
    RAISE E_ASSERT;
  END IF;

  -- Diagnostics cross a real SQL CALL boundary, not a mocked expression.
  BEGIN
    RAISE E_EXPECTED;
  EXCEPTION
    WHEN E_EXPECTED THEN
      CALL SP_FINOPS_FAIL_MODULE(:V_RUN_ID, 'ERRORS', :SQLCODE::STRING, :SQLERRM);
  END;
  SELECT ERROR_CODE, ERROR_MESSAGE INTO :V_ERROR_CODE, :V_ERROR_MESSAGE
  FROM FINOPS_MODULE_RUN WHERE RUN_ID = :V_RUN_ID AND MODULE_NAME = 'ERRORS';
  IF (V_ERROR_CODE <> '-20060' OR V_ERROR_MESSAGE <> 'Expected native diagnostic fixture.') THEN
    RAISE E_ASSERT;
  END IF;
  CALL SP_FINOPS_FAIL_MODULE(:V_RUN_ID, 'ERRORS', :V_ERROR_CODE, :V_ERROR_MESSAGE);
  SELECT COUNT(*) INTO :V_COUNT FROM FINOPS_FINDING
  WHERE RUN_ID = :V_RUN_ID AND MODULE_NAME = 'ERRORS' AND FINDING_TYPE = 'TECHNICAL_FAILURE';
  IF (V_COUNT <> 1) THEN RAISE E_ASSERT; END IF;

  CALL SP_FINOPS_COMPLETE_MODULE(:V_RUN_ID, 'AI', 'NORMAL', OBJECT_CONSTRUCT());
  CALL SP_FINOPS_COMPLETE_MODULE(:V_RUN_ID, 'COST', 'NORMAL', OBJECT_CONSTRUCT());
  CALL SP_FINOPS_COMPLETE_MODULE(:V_RUN_ID, 'OTHER_COSTS', 'NORMAL', OBJECT_CONSTRUCT());
  CALL SP_FINOPS_COMPLETE_MODULE(:V_RUN_ID, 'QUERIES', 'NORMAL', OBJECT_CONSTRUCT());
  CALL SP_FINOPS_COMPLETE_MODULE(:V_RUN_ID, 'WAREHOUSE', 'NORMAL', OBJECT_CONSTRUCT());
  CALL SP_FINOPS_BUILD_REPORT(:V_RUN_ID) INTO :V_RESULT;
  CALL SP_FINOPS_BUILD_REPORT(:V_RUN_ID);
  SELECT COUNT(*) INTO :V_COUNT FROM FINOPS_DAILY_REPORT WHERE RUN_ID = :V_RUN_ID;
  IF (V_COUNT <> 1 OR V_RESULT:overall_status::STRING <> 'FAILED') THEN
    RAISE E_ASSERT;
  END IF;
  V_LINES := 'AI: NORMAL\nCOST: NORMAL\nERRORS: FAILED\nOTHER_COSTS: NORMAL\nQUERIES: NORMAL\nWAREHOUSE: NORMAL';
  IF (POSITION(V_LINES IN V_RESULT:report_text::STRING) = 0
      OR V_RESULT:evidence_contract:actions_authorized::BOOLEAN <> FALSE) THEN
    RAISE E_ASSERT;
  END IF;
  SELECT COUNT(*) INTO :V_COUNT FROM FINOPS_ALERT_DELIVERY WHERE RUN_ID = :V_RUN_ID;
  IF (V_COUNT <> 0) THEN RAISE E_ASSERT; END IF;
  CALL SP_FINOPS_RECORD_RULE_GAP(:V_RUN_ID, 'AI', OBJECT_CONSTRUCT('fixture', 1), 'Fixture decision.');
  CALL SP_FINOPS_RECORD_RULE_GAP(:V_RUN_ID, 'AI', OBJECT_CONSTRUCT('fixture', 2), 'Fixture decision.');
  SELECT COUNT(*) INTO :V_COUNT FROM FINOPS_FINDING
  WHERE RUN_ID = :V_RUN_ID AND MODULE_NAME = 'AI' AND FINDING_TYPE = 'RULE_NOT_CONFIGURED'
    AND DETAILS:metrics:fixture::NUMBER = 2 AND DETAILS:required_decision::STRING = 'Fixture decision.';
  IF (V_COUNT <> 1) THEN RAISE E_ASSERT; END IF;

  -- Force a cast failure before integration/recipient lookup or SYSTEM$SEND_EMAIL.
  -- The uncommitted fixture cannot change another session's alert configuration.
  UPDATE FINOPS_CONFIG SET CONFIG_VALUE = TO_VARIANT('native-invalid-enabled')
  WHERE MODULE_NAME = 'ALERT' AND CONFIG_KEY = 'ENABLED';
  CALL SP_FINOPS_SEND_ALERT(:V_RUN_ID) INTO :V_RESULT;
  IF (V_RESULT:status::STRING <> 'FAILED') THEN RAISE E_ASSERT; END IF;
  CALL SP_FINOPS_SEND_ALERT(:V_RUN_ID) INTO :V_RESULT;
  SELECT COUNT(*) INTO :V_COUNT FROM FINOPS_ALERT_DELIVERY
  WHERE RUN_ID = :V_RUN_ID AND DELIVERY_STATUS = 'FAILED'
    AND ERROR_MESSAGE ILIKE '%native-invalid-enabled%';
  IF (V_COUNT <> 1 OR V_RESULT:status::STRING <> 'FAILED') THEN RAISE E_ASSERT; END IF;
  ROLLBACK;
  RETURN 'PASS: native diagnostics, decimal metrics, rule gaps, report newlines, pre-send alert failure; rolled back without email.';
EXCEPTION
  WHEN OTHER THEN
    ROLLBACK;
    RAISE;
END;
$$;
