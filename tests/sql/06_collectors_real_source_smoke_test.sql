-- Real Account Usage smoke; no email, finalizer, or lasting fixture records.
USE DATABASE FINOPS_DEV;
USE SCHEMA FINOPS;

EXECUTE IMMEDIATE $$
DECLARE
  V_RUN_ID STRING DEFAULT UUID_STRING();
  V_DAY DATE DEFAULT DATEADD(DAY, -1, TO_DATE(CONVERT_TIMEZONE('UTC', CURRENT_TIMESTAMP())));
  V_COUNT NUMBER;
  E_ASSERT EXCEPTION (-20062, 'Real-source collector smoke assertion failed.');
BEGIN
  BEGIN TRANSACTION;
  CALL SP_FINOPS_BEGIN_RUN(:V_RUN_ID, :V_DAY, CURRENT_TIMESTAMP());
  CALL SP_FINOPS_CHECK_COST(:V_RUN_ID, :V_DAY);
  CALL SP_FINOPS_CHECK_ERRORS(:V_RUN_ID, :V_DAY);
  CALL SP_FINOPS_CHECK_WAREHOUSE(:V_RUN_ID, :V_DAY);
  CALL SP_FINOPS_CHECK_QUERIES(:V_RUN_ID, :V_DAY);
  CALL SP_FINOPS_CHECK_AI(:V_RUN_ID, :V_DAY);
  CALL SP_FINOPS_CHECK_OTHER_COSTS(:V_RUN_ID, :V_DAY);
  CALL SP_FINOPS_BUILD_REPORT(:V_RUN_ID);
  SELECT COUNT(*) INTO :V_COUNT FROM FINOPS_MODULE_RUN
  WHERE RUN_ID = :V_RUN_ID AND STATUS IN ('NORMAL', 'REVIEW_REQUIRED', 'ATTENTION', 'DATA_INCOMPLETE', 'RULE_NOT_CONFIGURED');
  IF (V_COUNT <> 6) THEN RAISE E_ASSERT; END IF;
  SELECT COUNT(*) INTO :V_COUNT FROM FINOPS_METRIC WHERE RUN_ID = :V_RUN_ID;
  IF (V_COUNT <> 7) THEN RAISE E_ASSERT; END IF;
  SELECT COUNT(*) INTO :V_COUNT FROM FINOPS_DAILY_REPORT WHERE RUN_ID = :V_RUN_ID;
  IF (V_COUNT <> 1) THEN RAISE E_ASSERT; END IF;
  SELECT COUNT(*) INTO :V_COUNT FROM FINOPS_ALERT_DELIVERY WHERE RUN_ID = :V_RUN_ID;
  IF (V_COUNT <> 0) THEN RAISE E_ASSERT; END IF;
  ROLLBACK;
  RETURN 'PASS: six real-source collectors, seven metrics, one report, no email; rolled back.';
EXCEPTION
  WHEN OTHER THEN
    ROLLBACK;
    RAISE;
END;
$$;
