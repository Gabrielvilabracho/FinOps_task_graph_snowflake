USE DATABASE DATALAB;
USE SCHEMA SPAIN;

BEGIN TRANSACTION;

CALL SP_FINOPS_BEGIN_RUN('metric-contract-test', CURRENT_DATE(), CURRENT_TIMESTAMP());

CALL SP_FINOPS_RECORD_METRIC(
  'metric-contract-test', 'COST', 'DAILY_CREDITS', 'NORMAL',
  10, 8, NULL, NULL, 2, 0.25, 25, 'credits',
  ARRAY_CONSTRUCT(), 'Test explanation.', 'Test action.',
  'SNOWFLAKE.ACCOUNT_USAGE.METERING_HISTORY',
  DATEADD(DAY, -1, CURRENT_DATE())::TIMESTAMP_LTZ,
  CURRENT_DATE()::TIMESTAMP_LTZ,
  1, CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP(), TRUE, NULL
);

CALL SP_FINOPS_RECORD_METRIC(
  'metric-contract-test', 'COST', 'DAILY_CREDITS', 'ATTENTION',
  30, 10, NULL, NULL, 20, 2, 25, 'credits',
  ARRAY_CONSTRUCT(), 'Updated explanation.', 'Updated action.',
  'SNOWFLAKE.ACCOUNT_USAGE.METERING_HISTORY',
  DATEADD(DAY, -1, CURRENT_DATE())::TIMESTAMP_LTZ,
  CURRENT_DATE()::TIMESTAMP_LTZ,
  2, CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP(), TRUE, NULL
);

SELECT SYSTEM$ASSERT_EQUALS(
  1,
  (SELECT COUNT(*) FROM FINOPS_METRIC
   WHERE RUN_ID = 'metric-contract-test'
     AND MODULE_NAME = 'COST'
     AND METRIC_KEY = 'DAILY_CREDITS'),
  'Metric writes must merge by run, module, and metric key.'
);

SELECT SYSTEM$ASSERT_EQUALS(
  30::NUMBER,
  (SELECT CURRENT_VALUE FROM FINOPS_METRIC
   WHERE RUN_ID = 'metric-contract-test'
     AND MODULE_NAME = 'COST'
     AND METRIC_KEY = 'DAILY_CREDITS'),
  'Repeated metric writes must update the typed current value.'
);

ROLLBACK;
